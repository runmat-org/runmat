#!/usr/bin/env python3
"""Emit RunMat's Unicode 16 contextual-case property lookup.

Input is the official Unicode 16.0.0 DerivedCoreProperties.txt. The caller
pins its SHA-256; this script refuses a different file or Unicode version.
Generated ranges contain only Cased and Case_Ignorable, the two properties
needed to reproduce Rust 1.90 str::to_lowercase's final-sigma context.
The Unicode data license must accompany the generated source in the repo.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re


HEADER = re.compile(r"^# DerivedCoreProperties-16\.0\.0\.txt\s*$", re.MULTILINE)
SOURCE_SHA256 = "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd"
ROW = re.compile(
    r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(Cased|Case_Ignorable)\b",
    re.MULTILINE,
)


def merged_ranges(text: str, property_name: str) -> list[tuple[int, int]]:
    ranges = sorted(
        (int(first, 16), int(last or first, 16))
        for first, last, name in ROW.findall(text)
        if name == property_name
    )
    if not ranges:
        raise ValueError(f"no {property_name} property rows")
    merged: list[tuple[int, int]] = []
    for first, last in ranges:
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def emit_property(name: str, ranges: list[tuple[int, int]]) -> None:
    print("#[rustfmt::skip]")
    print(f"const {name}: &[(u32, u32)] = &[")
    for offset in range(0, len(ranges), 4):
        chunk = ranges[offset : offset + 4]
        print(
            "    "
            + " ".join(f"(0x{first:04X}, 0x{last:04X})," for first, last in chunk)
        )
    print("];")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    raw = args.source.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"DerivedCoreProperties SHA-256 mismatch: {digest}")
    text = raw.decode("utf-8")
    if not HEADER.search(text):
        raise ValueError("expected official Unicode 16.0.0 DerivedCoreProperties.txt")
    cased = merged_ranges(text, "Cased")
    ignorable = merged_ranges(text, "Case_Ignorable")
    print("//! Generated Unicode 16.0.0 contextual-case properties.")
    print("//!")
    print("//! Source: Unicode Consortium DerivedCoreProperties-16.0.0.txt.")
    print(f"//! Source SHA-256: {digest}.")
    print("//! Generated by scripts/generate_unicode16_case_properties.py.")
    print("//! Unicode data copyright and license: see crates/runmat-runtime/licenses/UNICODE-LICENSE.txt.")
    print("//!")
    print("//! Re-generate deliberately when the pinned Rust Unicode version changes.")
    print()
    emit_property("CASED", cased)
    emit_property("CASE_IGNORABLE", ignorable)
    print("fn contains(ranges: &[(u32, u32)], character: char) -> bool {")
    print("    let point = character as u32;")
    print("    let index = ranges.partition_point(|&(_, last)| last < point);")
    print("    ranges.get(index).is_some_and(|&(first, _)| first <= point)")
    print("}")
    print()
    print("pub(super) fn is_cased(character: char) -> bool {")
    print("    contains(CASED, character)")
    print("}")
    print()
    print("pub(super) fn is_case_ignorable(character: char) -> bool {")
    print("    contains(CASE_IGNORABLE, character)")
    print("}")


if __name__ == "__main__":
    main()
