#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const { parseDeclarations, rustFiles } = require("./fea-semantic-typegen/syntax.cjs");
const { renderReachable } = require("./fea-semantic-typegen/render.cjs");

const bindingsRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(bindingsRoot, "../..");
const scanRoots = [
  "crates/runmat-analysis/core/src",
  "crates/runmat-analysis/language/src",
  "crates/runmat-geometry/core/src",
  "crates/runmat-meshing/core/src",
  "crates/runmat-runtime/src/analysis/source",
  "crates/runmat-types/src",
].map((value) => path.join(repoRoot, value));
const output = path.join(bindingsRoot, "src/generated/fea-semantic-contracts.ts");

const registry = parseDeclarations(scanRoots.flatMap(rustFiles), {
  preferredDeclarations: {
    FieldLocation: "crates/runmat-analysis/core/src/study/output.rs",
  },
});
const body = renderReachable(registry, ["FeaSemanticProgram", "FeaSourceIndex"]);
if (/:\s*(?:unknown|any)\b|\b(?:unknown|any)\[\]/.test(body)) {
  throw new Error("Canonical FEA semantic bindings must not contain unknown or any fields");
}
const contents = [
  "// @generated by scripts/generate-fea-semantic-contracts.cjs",
  "// Do not edit by hand.",
  "",
  body,
  "",
].join("\n");
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, contents);
console.log(`Generated ${output}.`);
