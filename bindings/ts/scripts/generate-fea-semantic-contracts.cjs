#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const { parseDeclarations, rustFiles } = require("./fea-semantic-typegen/syntax.cjs");
const { renderReachable } = require("./fea-semantic-typegen/render.cjs");
const { renderGuards } = require("./fea-semantic-typegen/guards.cjs");
const { aliasDeclarations } = require("./fea-semantic-typegen/wire-integers.cjs");

const bindingsRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(bindingsRoot, "../..");
const scanRoots = [
  "crates/runmat-fea-source/src",
  "crates/runmat-analysis/core/src",
  "crates/runmat-analysis/language/src",
  "crates/runmat-geometry/core/src",
  "crates/runmat-meshing/core/src",
  "crates/runmat-runtime/src/analysis/source",
  "crates/runmat-types/src",
].map((value) => path.join(repoRoot, value));
const output = path.join(bindingsRoot, "src/generated/fea-semantic-contracts.ts");

const assessmentSources = [
  "crates/runmat-runtime/src/analysis/assessment.rs",
  "crates/runmat-analysis/fea/src/results/assessment.rs",
  "crates/runmat-analysis/fea/src/results/observation/entity.rs",
  "crates/runmat-analysis/fea/src/results/field/contract.rs",
].map((value) => path.join(repoRoot, value));
const registry = parseDeclarations([...scanRoots.flatMap(rustFiles), ...assessmentSources], {
  preferredDeclarations: {
    FieldLocation: "crates/runmat-analysis/core/src/study/output.rs",
  },
});
const contractBody = renderReachable(registry, ["FeaReassessmentRequest", "PublishedStudyReassessment", "PublishedCaseAssessments", "PublishedStudyAssessment", "CoordinateFrame", "FeaSemanticProgram", "FeaSourceIndex", "FeaSourceCheckResult", "FeaWorkspaceSnapshot", "FeaWorkspaceEdit", "FeaBrowseRequest", "FeaBrowsePage", "FeaBrowseOutcome", "FeaQueryError"], { externalTypes: ["FeaDiagnostic", "FeaCheckStatus"] });
// Every integer alias is declared here so the workspace contracts can import them.
const body = `${aliasDeclarations("WireU8 WireU16 WireU32 WireI8 WireI16 WireI32 WireU64 WireI64")}\n\n${contractBody}`;
if (/:\s*(?:unknown|any)\b|\b(?:unknown|any)\[\]/.test(body)) {
  throw new Error("Canonical FEA semantic bindings must not contain unknown or any fields");
}
const contents = [
  "// @generated by scripts/generate-fea-semantic-contracts.cjs",
  "// Do not edit by hand.",
  "import type { FeaDiagnostic, FeaCheckStatus } from './fea-analysis-contracts.js';",
  "",
  body,
  "",
].join("\n");
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, contents);
fs.writeFileSync(path.join(path.dirname(output), 'fea-assessment-guards.ts'),
  renderGuards(body, ['PublishedStudyAssessment', 'PublishedCaseAssessments', 'PublishedStudyReassessment', 'FeaSemanticProgram', 'FeaSourceCheckContract']));
const physicalUnitSource=fs.readFileSync(path.join(repoRoot,"crates/runmat-types/src/physical/unit.rs"),"utf8");
const lengthUnits=[...physicalUnitSource.matchAll(/pub const ([A-Z][A-Za-z0-9_]*):\s*Self\s*=\s*Self::catalog\(([0-9._]+)\);/g)];
if (!lengthUnits.length) throw new Error("Shared length-unit catalog did not expose any constants");
const dimension={length:1,mass:0,time:0,current:0,temperature:0,amount:0,luminous_intensity:0,information:0};
const values=Object.fromEntries(lengthUnits.map(match=>[match[1].replace(/([a-z])([A-Z])/g,"$1_$2").toLowerCase(),{dimension,scale:Number(match[2].replaceAll("_","")),offset:0}]));
fs.writeFileSync(path.join(path.dirname(output),"physical-unit-catalog.ts"),
  "// @generated from runmat-types physical unit constants; do not edit.\nimport type { LengthUnit } from './fea-semantic-contracts.js';\nexport const PHYSICAL_LENGTH_UNITS = "+JSON.stringify(values,null,2)+" as const satisfies Record<string, LengthUnit>;\n");
console.log(`Generated ${output}.`);
