#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "../../..");
const source = fs.readFileSync(
  path.join(root, "crates/runmat-execution/src/resource/mod.rs"), "utf8",
);
const name = "REMOTE_DRIVER_COMPLETION_CONTROL_BYTES";
const literal = source.match(new RegExp(`pub const ${name}: u64 = ([\\d_]+);`))?.[1];
const capacity = Number(literal?.replaceAll("_", ""));
if (!Number.isSafeInteger(capacity) || capacity <= 0) {
  throw new Error(`Invalid portable execution capacity ${name}`);
}
const contents = "// @generated by scripts/generate-execution-resources.cjs. Do not edit.\n" +
  `export const ${name} = ${capacity};\n`;
const output = path.join(root, "bindings/ts/src/execution/remote-driver-capacity.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== contents) {
    throw new Error("Execution resource capacities are stale; regenerate them from Rust");
  }
} else {
  fs.writeFileSync(output, contents);
}
