#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");
const { parseDeclarations } = require("./fea-semantic-typegen/syntax.cjs");
const { renderReachable } = require("./fea-semantic-typegen/render.cjs");
const root = path.resolve(__dirname, "../../..");
// Collaboration's JSON transport represents integer primitives as numbers.
// Its declarations do not use the FEA protocol's bounded-integer adapters.
const scalarTypes = new Map(
  ["u8", "u16", "u32", "u64", "usize", "i8", "i16", "i32", "i64", "isize"]
    .map((name) => [name, "number"]),
);
const declarations = parseDeclarations([
  path.join(root, "crates/runmat-plot/src/collaboration.rs"),
  path.join(root, "crates/runmat-filesystem/src/pinned/mod.rs"),
  path.join(root, "crates/runmat-filesystem/src/lib.rs"),
  path.join(root, "crates/runmat-filesystem/src/publication.rs"),
]);
const contents = "// @generated by scripts/generate-collaboration-contracts.cjs. Do not edit.\n\n" +
  renderReachable(declarations, ["PresenceFrame", "PointerPosition", "InputManifest", "AtomicCreateResult"], { scalarTypes }) + "\n";
const output = path.join(__dirname, "../src/generated/collaboration-contracts.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== contents) {
    throw new Error("Collaboration runtime contracts are stale; regenerate them from Rust");
  }
} else {
  fs.writeFileSync(output, contents);
}
