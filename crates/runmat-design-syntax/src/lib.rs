/// The `.fea` TextMate grammar, generated from the compiler's closed tables by
/// `scripts/docs/fea-grammar.mjs --write` (a docs test keeps this copy current). Docs, site code
/// cards and the language server all color `.fea` from this one grammar; its `vocabulary` key lists
/// the same word classes for hosts that classify lexer tokens.
pub const FEA_TEXTMATE_GRAMMAR: &str = include_str!("../grammar/fea.tmLanguage.json");

/// The design dialects' TextMate grammars, generated by the same `scripts/docs/fea-grammar.mjs`
/// from the dialect registry and each front end's statement registry (a docs test keeps them
/// current). One grammar per file kind; `.fea` is [`FEA_TEXTMATE_GRAMMAR`].
pub const DESIGN_TEXTMATE_GRAMMARS: &[(Dialect, &str)] = &[
    (
        Dialect::Part,
        include_str!("../grammar/part.tmLanguage.json"),
    ),
    (
        Dialect::Assembly,
        include_str!("../grammar/assembly.tmLanguage.json"),
    ),
    (
        Dialect::Drawing,
        include_str!("../grammar/drawing.tmLanguage.json"),
    ),
    (
        Dialect::Circuit,
        include_str!("../grammar/circuit.tmLanguage.json"),
    ),
    (
        Dialect::CircuitLayout,
        include_str!("../grammar/circuit.layout.tmLanguage.json"),
    ),
];

/// The TextMate grammar of a dialect.
pub fn textmate_grammar(dialect: Dialect) -> &'static str {
    if dialect == Dialect::Fea {
        return FEA_TEXTMATE_GRAMMAR;
    }
    DESIGN_TEXTMATE_GRAMMARS
        .iter()
        .find(|(each, _)| *each == dialect)
        .map(|(_, grammar)| *grammar)
        .expect("every design dialect has a grammar")
}
