//! Assembly and test outputs: IPC-D-356A netlist, bill of materials, pick-and-place.

use super::LengthUnit;
use crate::geom::Coord;
use serde::{Deserialize, Serialize};
use crate::layout::{Board, Footprint, Side};
use crate::library::PadKind;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// IPC-D-356A netlist (metric, 0.001 mm units).
pub fn ipc356(board: &Board) -> String {
    let n = board.copper_count();
    let mut s = String::new();
    let _ = writeln!(s, "C  IPC-D-356A netlist generated by RunMat");
    let _ = writeln!(s, "P  JOB   {}", board.name);
    let _ = writeln!(s, "P  UNITS CUST 1");
    let _ = writeln!(s, "P  DIM   N");
    let mut recs: Vec<String> = Vec::new();
    let num = |v: Coord| {
        let u = (v as f64 / 1000.0).round() as i64;
        format!(
            "{}{:06}",
            if u < 0 { '-' } else { '+' },
            u.abs().min(999_999)
        )
    };
    let sz = |v: Coord| format!("{:04}", ((v as f64 / 1000.0).round() as i64).clamp(0, 9999));
    for f in board.footprints.values() {
        for (pd, pp) in f.package.pads.iter().zip(f.pads(n)) {
            let Some(net) = pp.net else { continue };
            let name: String = board.net_name(net).chars().take(14).collect();
            let thru = pd.kind == PadKind::Tht;
            let code = if thru { "317" } else { "327" };
            let access: String = if thru {
                "A00".into()
            } else if f.side == Side::Top {
                "A01".into()
            } else {
                format!("A{n:02}")
            };
            let b = pp.prim.bbox();
            let drill = match pd.drill.as_ref() {
                Some(d) => format!("D{}{}", sz(d.diameter), if d.plated { 'P' } else { 'U' }),
                None => "      ".into(),
            };
            let rot = (f.transform().apply_angle(pd.rotation).round() as i64).rem_euclid(360);
            recs.push(format!(
                "{code}{name:<14}   {:<6}-{:<4} {drill}{access}X{}Y{}X{}Y{}R{:03} S{}",
                f.reference.chars().take(6).collect::<String>(),
                pd.name.chars().take(4).collect::<String>(),
                num(pp.center.x),
                num(pp.center.y),
                sz(b.width()),
                sz(b.height()),
                rot,
                if pd.mask { 0 } else { 3 }
            ));
        }
    }
    for v in board.vias.values() {
        let Some(net) = v.net else { continue };
        let name: String = board.net_name(net).chars().take(14).collect();
        recs.push(format!(
            "317{name:<14}   VIA   -     D{}PA00X{}Y{}X{}Y{}R000 S{}",
            sz(v.drill),
            num(v.at.x),
            num(v.at.y),
            sz(v.diameter),
            sz(v.diameter),
            if v.tented { 3 } else { 0 }
        ));
    }
    recs.sort();
    for r in recs {
        s.push_str(&r);
        s.push('\n');
    }
    s.push_str("999\n");
    s
}

/// Natural sort key: `R2` < `R10`.
pub fn natural_key(s: &str) -> (String, u64, String) {
    let p: String = s.chars().take_while(|c| !c.is_ascii_digit()).collect();
    let rest = &s[p.len()..];
    let d: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
    (p, d.parse().unwrap_or(0), rest[d.len()..].to_string())
}

fn csv(fields: &[String]) -> String {
    fields
        .iter()
        .map(|f| {
            if f.contains([',', '"', '\n']) {
                format!("\"{}\"", f.replace('"', "\"\""))
            } else {
                f.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(",")
}

/// A BOM line.
#[derive(Clone, Debug, PartialEq)]
pub struct BomLine {
    pub designators: Vec<String>,
    pub quantity: usize,
    pub value: String,
    pub package: String,
    pub mpn: String,
    pub manufacturer: String,
}

/// A component's value as BOMs and netlists print it: its `Value` property, else its
/// resistance, capacitance, inductance or frequency with an engineering prefix (`12 pF`).
pub fn component_value(c: &crate::elab::CompInst) -> String {
    c.properties
        .get("Value")
        .cloned()
        .or_else(|| {
            ["resistance", "capacitance", "inductance", "frequency"]
                .iter()
                .find_map(|k| {
                    c.params.get(*k).map(|p| match &p.value {
                        crate::ir::ParamValue::Quantity { nominal, .. } => {
                            crate::index::quantity_display(nominal.value, nominal.dim)
                        }
                        crate::ir::ParamValue::Text(t) => t.clone(),
                        crate::ir::ParamValue::Bool(b) => b.to_string(),
                    })
                })
        })
        .unwrap_or_default()
}

/// Grouped, variant-aware BOM from an elaborated netlist (not-fitted parts are left out;
/// alternates appear with their own part).
pub fn bom(nl: &crate::elab::Netlist, pool: &crate::library::Pool) -> Vec<BomLine> {
    let mut groups: BTreeMap<(String, String, String, String), Vec<String>> = BTreeMap::new();
    for c in nl.components.iter().filter(|c| c.fitted()) {
        let part = c.part.and_then(|u| pool.parts.get(&u));
        let pkg = c
            .package
            .and_then(|u| pool.packages.get(&u))
            .map(|p| p.name.clone())
            .unwrap_or_default();
        let value = component_value(c);
        let key = (
            part.map(|p| p.mpn.clone()).unwrap_or_default(),
            value,
            pkg,
            part.map(|p| p.manufacturer.clone()).unwrap_or_default(),
        );
        groups.entry(key).or_default().push(c.designator.clone());
    }
    let mut out: Vec<BomLine> = groups
        .into_iter()
        .map(|((mpn, value, package, manufacturer), mut d)| {
            d.sort_by_key(|x| natural_key(x));
            BomLine {
                quantity: d.len(),
                designators: d,
                value,
                package,
                mpn,
                manufacturer,
            }
        })
        .collect();
    out.sort_by_key(|l| natural_key(&l.designators[0]));
    out
}

/// A column of the bill of materials.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BomColumn {
    Designators,
    Quantity,
    Value,
    Package,
    Mpn,
    Manufacturer,
}

impl BomColumn {
    pub const ALL: [BomColumn; 6] = [
        BomColumn::Designators,
        BomColumn::Quantity,
        BomColumn::Value,
        BomColumn::Package,
        BomColumn::Mpn,
        BomColumn::Manufacturer,
    ];
    pub fn word(self) -> &'static str {
        match self {
            BomColumn::Designators => "designators",
            BomColumn::Quantity => "quantity",
            BomColumn::Value => "value",
            BomColumn::Package => "package",
            BomColumn::Mpn => "mpn",
            BomColumn::Manufacturer => "manufacturer",
        }
    }
    pub fn from_word(word: &str) -> Option<BomColumn> {
        BomColumn::ALL.into_iter().find(|c| c.word() == word)
    }
    fn header(self) -> &'static str {
        match self {
            BomColumn::Designators => "Designators",
            BomColumn::Quantity => "Quantity",
            BomColumn::Value => "Value",
            BomColumn::Package => "Package",
            BomColumn::Mpn => "MPN",
            BomColumn::Manufacturer => "Manufacturer",
        }
    }
    fn cell(self, l: &BomLine) -> String {
        match self {
            BomColumn::Designators => l.designators.join(" "),
            BomColumn::Quantity => l.quantity.to_string(),
            BomColumn::Value => l.value.clone(),
            BomColumn::Package => l.package.clone(),
            BomColumn::Mpn => l.mpn.clone(),
            BomColumn::Manufacturer => l.manufacturer.clone(),
        }
    }
}

/// How the bill of materials is written: its columns, in order, and whether parts with the
/// same part number, value and package share a line (else one line per designator).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct BomFormat {
    pub columns: Vec<BomColumn>,
    pub group_by_value: bool,
}

impl Default for BomFormat {
    fn default() -> Self {
        BomFormat { columns: BomColumn::ALL.to_vec(), group_by_value: true }
    }
}

/// The bill of materials as CSV, every column, grouped.
pub fn bom_csv(lines: &[BomLine]) -> String {
    bom_csv_in(lines, &BomFormat::default())
}

/// The bill of materials as CSV in `format`. Ungrouped, each designator has its own line
/// (quantity 1), in designator order.
pub fn bom_csv_in(lines: &[BomLine], format: &BomFormat) -> String {
    let columns = if format.columns.is_empty() { BomColumn::ALL.to_vec() } else { format.columns.clone() };
    let mut rows: Vec<BomLine> = if format.group_by_value {
        lines.to_vec()
    } else {
        let mut one: Vec<BomLine> = lines
            .iter()
            .flat_map(|l| l.designators.iter().map(move |d| BomLine { designators: vec![d.clone()], quantity: 1, ..l.clone() }))
            .collect();
        one.sort_by_key(|l| natural_key(&l.designators[0]));
        one
    };
    rows.retain(|l| !l.designators.is_empty());
    let mut s = csv(&columns.iter().map(|c| c.header().to_string()).collect::<Vec<_>>());
    s.push('\n');
    for l in &rows {
        s.push_str(&csv(&columns.iter().map(|c| c.cell(l)).collect::<Vec<_>>()));
        s.push('\n');
    }
    s
}

/// Which sides the pick-and-place lists, and in how many files.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PlaceSides {
    /// Both sides in one file, with a side column.
    #[default]
    Both,
    /// One file per side.
    Separate,
    Top,
    Bottom,
}

impl PlaceSides {
    pub const ALL: [PlaceSides; 4] = [PlaceSides::Both, PlaceSides::Separate, PlaceSides::Top, PlaceSides::Bottom];
    pub fn word(self) -> &'static str {
        match self {
            PlaceSides::Both => "both",
            PlaceSides::Separate => "separate",
            PlaceSides::Top => "top",
            PlaceSides::Bottom => "bottom",
        }
    }
    pub fn from_word(word: &str) -> Option<PlaceSides> {
        PlaceSides::ALL.into_iter().find(|s| s.word() == word)
    }
    /// The files: a name suffix (`""`, `-top`, `-bottom`) and the side each lists (`None`: both).
    pub fn files(self) -> Vec<(&'static str, Option<Side>)> {
        match self {
            PlaceSides::Both => vec![("", None)],
            PlaceSides::Separate => vec![("-top", Some(Side::Top)), ("-bottom", Some(Side::Bottom))],
            PlaceSides::Top => vec![("-top", Some(Side::Top))],
            PlaceSides::Bottom => vec![("-bottom", Some(Side::Bottom))],
        }
    }
}

/// How the pick-and-place is written: the sides and the unit of the positions.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct PickPlaceFormat {
    pub sides: PlaceSides,
    pub units: LengthUnit,
}

/// Pick-and-place CSV for fitted footprints (SMD only unless `include_tht`), origin at the
/// outline's lower-left corner, rotation counter-clockwise as seen from the top.
pub fn pick_place(board: &Board, include_tht: bool) -> String {
    pick_place_of(board, include_tht, None)
}

/// [`pick_place`] for a variant: `fitted` names the designators the variant fits (the board's
/// own fitting when `None`).
pub fn pick_place_of(
    board: &Board,
    include_tht: bool,
    fitted: Option<&std::collections::BTreeSet<String>>,
) -> String {
    pick_place_in(board, include_tht, fitted, None, LengthUnit::Mm)
}

/// [`pick_place_of`] for one side (`None`: both) with positions in `units` (4 decimals in
/// millimetres, 5 in inches).
pub fn pick_place_in(
    board: &Board,
    include_tht: bool,
    fitted: Option<&std::collections::BTreeSet<String>>,
    side: Option<Side>,
    units: LengthUnit,
) -> String {
    let origin = board.outline.bbox().min;
    let pos = |v: Coord| match units {
        LengthUnit::Mm => format!("{:.4}", units.of(v)),
        LengthUnit::Inch => format!("{:.5}", units.of(v)),
    };
    let mut rows: Vec<(Footprint, String)> = Vec::new();
    let is_fitted = |f: &Footprint| fitted.map_or(f.fitted, |s| s.contains(&f.reference));
    for f in board
        .footprints
        .values()
        .filter(|f| is_fitted(f) && (f.package.smd || include_tht) && side.map_or(true, |s| f.side == s))
    {
        let p = f.at - origin;
        rows.push((
            f.clone(),
            csv(&[
                f.reference.clone(),
                f.value.clone(),
                f.package.name.clone(),
                pos(p.x),
                pos(p.y),
                format!("{:.2}", f.rotation),
                if f.side == Side::Top {
                    "top".into()
                } else {
                    "bottom".into()
                },
            ]),
        ));
    }
    rows.sort_by_key(|(f, _)| natural_key(&f.reference));
    let u = match units {
        LengthUnit::Mm => "mm",
        LengthUnit::Inch => "in",
    };
    let mut s = format!("Designator,Value,Package,X_{u},Y_{u},Rotation,Side\n");
    for (_, r) in rows {
        s.push_str(&r);
        s.push('\n');
    }
    s
}
