//! The single public option-spelling grammar, shared by every solver profile.
use super::OptimOptionField;
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum OptionSpelling {
    Field(OptimOptionField),
}
impl OptionSpelling {
    pub(super) fn field(self) -> OptimOptionField {
        match self {
            Self::Field(field) => field,
        }
    }
    pub(super) fn parse(name: &str) -> Option<Self> {
        use OptimOptionField as Field;
        Some(match name.to_ascii_lowercase().as_str() {
            "tolx" | "steptolerance" => Self::Field(Field::TolX),
            "tolfun" => Self::Field(Field::TolFun),
            "optimalitytolerance" => Self::Field(Field::OptimalityTolerance),
            "tolcon" | "constrainttolerance" => Self::Field(Field::TolCon),
            "functiontolerance" => Self::Field(Field::FunctionTolerance),
            "maxiter" | "maxiterations" => Self::Field(Field::MaxIter),
            "maxfunevals" | "maxfunctionevaluations" => Self::Field(Field::MaxFunEvals),
            "display" => Self::Field(Field::Display),
            "algorithm" => Self::Field(Field::Algorithm),
            "specifyobjectivegradient" | "gradobj" => Self::Field(Field::SpecifyObjectiveGradient),
            "specifyconstraintgradient" | "gradconstr" => {
                Self::Field(Field::SpecifyConstraintGradient)
            }
            "finitedifferencetype" | "findifftype" => Self::Field(Field::FiniteDifferenceType),
            "finitedifferencestepsize" | "findiffrelstep" => {
                Self::Field(Field::FiniteDifferenceStepSize)
            }
            "typicalx" => Self::Field(Field::TypicalX),
            "outputfcn" | "outputfcns" => Self::Field(Field::OutputFcn),
            "hessianfcn" => Self::Field(Field::HessianFcn),
            "jacobianmultiplyfcn" | "jacobmult" => Self::Field(Field::JacobianMultiplyFcn),
            "hessianmultiplyfcn" => Self::Field(Field::HessianMultiplyFcn),
            "hesspattern" => Self::Field(Field::HessPattern),
            "maxpcgiter" => Self::Field(Field::MaxPCGIter),
            "tolpcg" => Self::Field(Field::TolPCG),
            "precondbandwidth" => Self::Field(Field::PrecondBandWidth),
            "subproblemalgorithm" => Self::Field(Field::SubproblemAlgorithm),
            "absolutegaptolerance" => Self::Field(Field::AbsoluteGapTolerance),
            "relativegaptolerance" => Self::Field(Field::RelativeGapTolerance),
            "maxfeasiblepoints" => Self::Field(Field::MaxFeasiblePoints),
            "maxnodes" => Self::Field(Field::MaxNodes),
            "maxtime" | "timelimit" => Self::Field(Field::MaxTime),
            "objectivecutoff" => Self::Field(Field::ObjectiveCutOff),
            "plotfcn" => Self::Field(Field::PlotFcn),
            "hessianapproximation" => Self::Field(Field::HessianApproximation),
            "hessupdate" => Self::Field(Field::HessUpdate),
            "objectivelimit" => Self::Field(Field::ObjectiveLimit),
            "useparallel" => Self::Field(Field::UseParallel),
            "absolutemaxobjectivecount" => Self::Field(Field::AbsoluteMaxObjectiveCount),
            "equalitygoalcount" | "goalsexactachieve" => Self::Field(Field::EqualityGoalCount),
            "meritfunction" => Self::Field(Field::MeritFunction),
            "diagnostics" => Self::Field(Field::Diagnostics),
            "diffmaxchange" => Self::Field(Field::DiffMaxChange),
            "diffminchange" => Self::Field(Field::DiffMinChange),
            "funvalcheck" => Self::Field(Field::FunValCheck),
            "maxsqpiter" => Self::Field(Field::MaxSQPIter),
            "rellinesrchbnd" => Self::Field(Field::RelLineSrchBnd),
            "rellinesrchbndduration" => Self::Field(Field::RelLineSrchBndDuration),
            "tolconsqp" => Self::Field(Field::TolConSQP),
            "plotfcns" => Self::Field(Field::PlotFcn),
            "creationfcn" => Self::Field(Field::CreationFcn),
            "hybridfcn" => Self::Field(Field::HybridFcn),
            "displayinterval" => Self::Field(Field::DisplayInterval),
            "inertiarange" => Self::Field(Field::InertiaRange),
            "initialpoints" => Self::Field(Field::InitialPoints),
            "batchupdateinterval" => Self::Field(Field::BatchUpdateInterval),
            "checkpointfile" => Self::Field(Field::CheckpointFile),
            "minsampledistance" => Self::Field(Field::MinSampleDistance),
            "minsurrogatepoints" => Self::Field(Field::MinSurrogatePoints),
            "initialswarmspan" => Self::Field(Field::InitialSwarmSpan),
            "maxstalliterations" => Self::Field(Field::MaxStallIterations),
            "maxstalltime" => Self::Field(Field::MaxStallTime),
            "minneighborsfraction" => Self::Field(Field::MinNeighborsFraction),
            "selfadjustmentweight" => Self::Field(Field::SelfAdjustmentWeight),
            "socialadjustmentweight" => Self::Field(Field::SocialAdjustmentWeight),
            "swarmsize" => Self::Field(Field::SwarmSize),
            "acceptancefcn" => Self::Field(Field::AcceptanceFcn),
            "annealingfcn" => Self::Field(Field::AnnealingFcn),
            "datatype" => Self::Field(Field::DataType),
            "hybridinterval" => Self::Field(Field::HybridInterval),
            "initialtemperature" => Self::Field(Field::InitialTemperature),
            "reannealinterval" => Self::Field(Field::ReannealInterval),
            "populationtype" => Self::Field(Field::PopulationType),
            "populationsize" => Self::Field(Field::PopulationSize),
            "elitecount" => Self::Field(Field::EliteCount),
            "crossoverfraction" => Self::Field(Field::CrossoverFraction),
            "initialpopulationmatrix" => Self::Field(Field::InitialPopulationMatrix),
            "initialscoresmatrix" => Self::Field(Field::InitialScoresMatrix),
            "initialpopulationrange" => Self::Field(Field::InitialPopulationRange),
            "crossoverfcn" => Self::Field(Field::CrossoverFcn),
            "mutationfcn" => Self::Field(Field::MutationFcn),
            "selectionfcn" => Self::Field(Field::SelectionFcn),
            "fitnessscalingfcn" => Self::Field(Field::FitnessScalingFcn),
            "nonlinearconstraintalgorithm" => Self::Field(Field::NonlinearConstraintAlgorithm),
            "migrationdirection" => Self::Field(Field::MigrationDirection),
            "migrationfraction" => Self::Field(Field::MigrationFraction),
            "migrationinterval" => Self::Field(Field::MigrationInterval),
            "stalltest" => Self::Field(Field::StallTest),
            "maxgenerations" | "generations" => Self::Field(Field::MaxIter),
            "maxstallgenerations" | "stallgenlimit" => Self::Field(Field::MaxStallIterations),
            "fitnesslimit" => Self::Field(Field::ObjectiveLimit),
            "initialpopulation" => Self::Field(Field::InitialPopulationMatrix),
            "initialscores" => Self::Field(Field::InitialScoresMatrix),
            "popinitrange" => Self::Field(Field::InitialPopulationRange),
            "temperaturefcn" => Self::Field(Field::TemperatureFcn),
            "initialswarmmatrix" | "initialswarm" => Self::Field(Field::InitialPoints),
            "hessfcn" => Self::Field(Field::HessianFcn),
            "hessmult" => Self::Field(Field::HessianMultiplyFcn),
            "meshtolerance" | "tolmesh" => Self::Field(Field::MeshTolerance),
            "initialmeshsize" => Self::Field(Field::InitialMeshSize),
            "maxmeshsize" => Self::Field(Field::MaxMeshSize),
            "meshcontractionfactor" | "meshcontraction" => {
                Self::Field(Field::MeshContractionFactor)
            }
            "meshexpansionfactor" | "meshexpansion" => Self::Field(Field::MeshExpansionFactor),
            "meshrotate" => Self::Field(Field::MeshRotate),
            "acceleratemesh" => Self::Field(Field::AccelerateMesh),
            "scalemesh" => Self::Field(Field::ScaleMesh),
            "pollmethod" => Self::Field(Field::PollMethod),
            "pollorderalgorithm" | "pollingorder" => Self::Field(Field::PollOrderAlgorithm),
            "usecompletepoll" | "completepoll" => Self::Field(Field::UseCompletePoll),
            "searchfcn" | "searchmethod" => Self::Field(Field::SearchFcn),
            "usecompletesearch" | "completesearch" => Self::Field(Field::UseCompleteSearch),
            "tolbind" => Self::Field(Field::TolBind),
            "initialpenalty" => Self::Field(Field::InitialPenalty),
            "penaltyfactor" => Self::Field(Field::PenaltyFactor),
            "cache" => Self::Field(Field::Cache),
            "cachesize" => Self::Field(Field::CacheSize),
            "cachetol" => Self::Field(Field::CacheTol),
            "plotinterval" => Self::Field(Field::PlotInterval),
            "usevectorized" | "vectorized" => Self::Field(Field::UseVectorized),
            _ => return None,
        })
    }
}
