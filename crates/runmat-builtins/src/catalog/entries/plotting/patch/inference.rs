use crate::{
    catalog::inference::{argument_error, finish_fixed},
    BuiltinCatalogEntry,
};
use runmat_types::*;

pub(super) fn infer(request: &CallRequest, entry: &BuiltinCatalogEntry) -> CallInference {
    let mut diagnostics = Vec::new();
    if request.arguments.is_empty() {
        diagnostics.push(argument_error(
            "RM-CATALOG-PATCH-DATA",
            "patch requires coordinates, Faces/Vertices, or a graphics property struct",
            0,
        ));
    }
    // Geometry, axes aliases, and property pairs are structurally distinct
    // forms. The plotting admission owner validates their exact cardinality
    // without guessing from a scalar numeric first argument here.
    finish_fixed(
        entry,
        request,
        ValueFact::scalar(ValueKindFact::Numeric(NumericFact {
            class: NumericClass::Double,
            domain: NumericDomain::Real,
        })),
        diagnostics,
    )
}
