/// RunMat statements that build `part`, `steel`, and `model` for the box
/// study: steel bulk material, a fixed `x = 0` face, and a 1 kN `+x` force on
/// the `x = 1 m` face in one static step. Shared by every FEA example that
/// needs a model so the examples stay consistent with `box_static.fea`.
macro_rules! fea_box_model_setup {
    () => {
        concat!(
            "part = geometry.load(\"box.brep\", \"Units\", \"m\");\n",
            "steel = fea.material(\"steel\", \"YoungsModulusPa\", 200e9, \"PoissonRatio\", 0.3, \"MassDensityKgPerM3\", 7850);\n",
            "body = fea.materialAssignment(fea.PropertyRegionTarget.allSolids(part), steel);\n",
            "support = fea.StructuralConstraint.fixed(\"support\", geometry.region(part, \"face_000001\"));\n",
            "tipForce = fea.ForceSignal.constantNewtons(\"tip_force\", [1000 0 0]);\n",
            "tipLoad = fea.StructuralExcitation.force(\"tip_load\", geometry.region(part, \"face_000002\"), tipForce);\n",
            "service = fea.ExcitationCase.always(\"service\", {tipLoad});\n",
            "staticStep = fea.StructuralStep.static(\"static\");\n",
            "model = fea.model(\"box_model\", part, \"Materials\", {steel}, \"MaterialAssignments\", {body}, ...\n",
            "    \"Constraints\", {support}, \"Signals\", {tipForce}, \"Excitations\", {tipLoad}, ...\n",
            "    \"ExcitationCases\", {service}, \"Steps\", {staticStep});\n",
        )
    };
}
pub(crate) use fea_box_model_setup;

/// `fea_box_model_setup!` followed by a meshed study `study` and its solved
/// aggregate `run`. Requires a native host with meshing available.
macro_rules! fea_box_run_setup {
    () => {
        concat!(
            $crate::fea_contract::example_fixtures::fea_box_model_setup!(),
            "solverMesh = meshing.generate(part, \"TargetSize\", 0.5, \"MaximumDeviation\", 0.05, \"ElementOrder\", \"tet4\");\n",
            "sequence = fea.AnalysisSequence.new(\"box_model.sequence\", {staticStep}, {}, {}, {});\n",
            "plan = fea.ExecutionPlan.defaults(sequence, fea.ComputeBackend.cpu());\n",
            "study = fea.study(\"box_static\", part, model, \"Mesh\", solverMesh, \"Execution\", plan);\n",
            "run = fea.run(study);\n",
        )
    };
}
pub(crate) use fea_box_run_setup;

