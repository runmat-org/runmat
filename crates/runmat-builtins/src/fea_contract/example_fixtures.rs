/// The scripted study below, authored in the `.fea` language.
pub const BOX_STATIC_FEA: &str = concat!(
    "geometry box {\n",
    "    file = \"./box.brep\"\n",
    "    units = m\n",
    "    region body : solid { select id \"solid_000001\"; expect exactly_one }\n",
    "    region support : face { select id \"face_000001\"; expect exactly_one }\n",
    "    region tip : face { select id \"face_000002\"; expect exactly_one }\n",
    "}\n",
    "\n",
    "mesh box on geometry.box {\n",
    "    tetrahedra {\n",
    "        order = linear\n",
    "        target_size = 0.5 m\n",
    "        maximum_deviation = 0.05 m\n",
    "    }\n",
    "}\n",
    "\n",
    "material steel {\n",
    "    mass_density = 7850 kg/m^3\n",
    "    elastic {\n",
    "        youngs_modulus = 200 GPa\n",
    "        poisson_ratio = 0.3\n",
    "    }\n",
    "}\n",
    "\n",
    "model loaded_box {\n",
    "    assign material.steel to geometry.box.region.body\n",
    "    constraint support {\n",
    "        structural.fixed { target = geometry.box.region.support }\n",
    "    }\n",
    "    load tip_traction {\n",
    "        traction on geometry.box.region.tip = [166.6666666667, 0, 0] Pa\n",
    "    }\n",
    "    load_case service { include load.tip_traction }\n",
    "}\n",
    "\n",
    "study box_static {\n",
    "    geometry = geometry.box\n",
    "    mesh = mesh.box\n",
    "    model = model.loaded_box\n",
    "    analysis static { structural static {} }\n",
    "    output displacement = analysis.static.field.node.displacement\n",
    "    output von_mises = analysis.static.field.element.von_mises_stress\n",
    "}\n",
);

