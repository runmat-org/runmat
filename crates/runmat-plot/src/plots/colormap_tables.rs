/// Linear interpolation through an evenly spaced table, `t` in [0, 1].
pub(crate) fn sample(table: &[[f32; 3]], t: f32) -> [f32; 3] {
    let last = table.len() - 1;
    let x = if t.is_finite() {
        t.clamp(0.0, 1.0)
    } else {
        0.0
    } * last as f32;
    let i = (x.floor() as usize).min(last.saturating_sub(1));
    let f = x - i as f32;
    let (a, b) = (table[i], table[(i + 1).min(last)]);
    [
        a[0] + (b[0] - a[0]) * f,
        a[1] + (b[1] - a[1]) * f,
        a[2] + (b[2] - a[2]) * f,
    ]
}

#[cfg(test)]
mod tests {
    use super::{PLASMA, VIRIDIS};

    #[test]
    fn fixed_point_samples_preserve_original_channel_bits() {
        for (actual, original) in [
            (VIRIDIS[37], ["0.1281", "0.6477", "0.5235"]),
            (VIRIDIS[47], ["0.3524", "0.7830", "0.3926"]),
            (PLASMA[17], ["0.5236", "0.0245", "0.6529"]),
        ] {
            assert_eq!(
                actual.map(f32::to_bits),
                original.map(|channel| channel.parse::<f32>().unwrap().to_bits())
            );
        }
    }
}
