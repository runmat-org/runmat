/// Four-decimal RGB samples are color data, not approximations of angle constants.
const fn rgb_1e4(channels: [u16; 3]) -> [f32; 3] {
    [
        channels[0] as f32 / 10_000.0,
        channels[1] as f32 / 10_000.0,
        channels[2] as f32 / 10_000.0,
    ]
}

