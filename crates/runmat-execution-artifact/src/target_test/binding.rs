use runmat_execution::host::NativeSelectedProductBinding;
use runmat_execution::{Digest, ProgramFunctionId, ProgramRevision};
use runmat_test::identity::{SuiteId, TestId};
use runmat_types::FunctionId;
use serde::{Deserialize, Serialize};

use crate::program::{
    ExecutableForm, ProgramArtifact, ProgramArtifactId, ProgramBuildRecipe, ProgramProductMode,
};
use crate::{ArtifactError, ArtifactResult};

use super::{canonical_bytes, decode_canonical};

pub const NATIVE_PAIRED_TEST_SCHEMA_VERSION: u16 = 2;
const MAX_TEST_ENTRIES: usize = 65_536;

/// Semantic function and compiled body, to be compared with the actual linked
/// entry map by each product receiver. Neither a label nor this declaration
/// alone authorizes a call.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativeCompiledEntry {
    /// Immutable semantic identity used by origins and source selection.
    pub function: ProgramFunctionId,
    /// Session compiler coordinate used only to resolve the linked body.
    pub compiled_function: FunctionId,
    pub body: Digest,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativeTestEntry {
    pub suite: SuiteId,
    pub test: TestId,
    pub compiled: NativeCompiledEntry,
}

/// Shared before linking either product. Concrete object/artifact digests are
/// deliberately excluded, avoiding a self-referential artifact hash cycle.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativePairedBuildBinding {
    pub schema_version: u16,
    pub program_revision: ProgramRevision,
    pub selected_product: NativeSelectedProductBinding,
    pub application: NativeCompiledEntry,
    pub tests: Vec<NativeTestEntry>,
}

impl NativePairedBuildBinding {
    pub fn validate(&self) -> ArtifactResult<()> {
        if self.schema_version != NATIVE_PAIRED_TEST_SCHEMA_VERSION
            || self.tests.is_empty()
            || self.tests.len() > MAX_TEST_ENTRIES
            || zero(self.application.body)
        {
            return Err(invalid("invalid paired native build binding"));
        }
        self.program_revision
            .validate()
            .map_err(crate::error::contract_error)?;
        self.selected_product
            .validate()
            .map_err(crate::error::contract_error)?;
        if *self.program_revision.runtime_fingerprint() != self.selected_product.runtime
            || *self.program_revision.catalog_fingerprint() != self.selected_product.catalog
        {
            return Err(invalid(
                "paired program environment differs from selected product",
            ));
        }
        for entry in &self.tests {
            if entry.suite.validate().is_err()
                || entry.test.validate().is_err()
                || zero(entry.compiled.body)
            {
                return Err(invalid("invalid paired native test entry"));
            }
        }
        if self
            .tests
            .windows(2)
            .any(|pair| (&pair[0].suite, &pair[0].test) >= (&pair[1].suite, &pair[1].test))
        {
            return Err(invalid("test entries must be sorted and unique"));
        }
        let mut bodies = std::collections::BTreeMap::from([(
            self.application.compiled_function,
            (self.application.function, self.application.body),
        )]);
        let mut semantic_bodies = std::collections::BTreeMap::from([(
            self.application.function,
            (self.application.compiled_function, self.application.body),
        )]);
        for entry in &self.tests {
            if bodies
                .insert(
                    entry.compiled.compiled_function,
                    (entry.compiled.function, entry.compiled.body),
                )
                .is_some_and(|body| body != (entry.compiled.function, entry.compiled.body))
            {
                return Err(invalid("one test function has conflicting compiled bodies"));
            }
            if semantic_bodies
                .insert(
                    entry.compiled.function,
                    (entry.compiled.compiled_function, entry.compiled.body),
                )
                .is_some_and(|body| body != (entry.compiled.compiled_function, entry.compiled.body))
            {
                return Err(invalid(
                    "one semantic function has conflicting compiled coordinates",
                ));
            }
        }
        // The suite/test identities are generated by runmat-test. Their wire
        // shape is checked here; derivation from the authenticated test plan is
        // a separate receiver/build-system comparison.
        Ok(())
    }

    pub fn digest(&self) -> ArtifactResult<Digest> {
        self.validate()?;
        Ok(Digest::sha256(
            [
                b"runmat-native-paired-build-v2\0".as_slice(),
                &canonical_bytes(self)?,
            ]
            .concat(),
        ))
    }

    pub fn to_canonical_bytes(&self) -> ArtifactResult<Vec<u8>> {
        self.validate()?;
        canonical_bytes(self)
    }

    pub fn from_canonical_bytes(bytes: &[u8]) -> ArtifactResult<Self> {
        let value: Self = decode_canonical(bytes)?;
        value.validate()?;
        Ok(value)
    }

    pub fn test(&self, suite: &SuiteId, test: &TestId) -> Option<&NativeTestEntry> {
        self.tests
            .iter()
            .find(|entry| &entry.suite == suite && &entry.test == test)
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum NativePairedProductRole {
    Application,
    Test,
}

/// To be embedded in a product and checked against its exact linked entry map.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativePairedProductHeader {
    pub schema_version: u16,
    pub role: NativePairedProductRole,
    pub binding: NativePairedBuildBinding,
    pub linked_entries: Vec<NativeCompiledEntry>,
}

impl NativePairedProductHeader {
    pub fn validate(&self) -> ArtifactResult<()> {
        self.binding.validate()?;
        if self.schema_version != NATIVE_PAIRED_TEST_SCHEMA_VERSION {
            return Err(invalid("unsupported paired native product header"));
        }
        let expected: Vec<_> = match self.role {
            NativePairedProductRole::Application => vec![self.binding.application.clone()],
            NativePairedProductRole::Test => self
                .binding
                .tests
                .iter()
                .map(|entry| (entry.compiled.compiled_function, entry.compiled.clone()))
                .collect::<std::collections::BTreeMap<_, _>>()
                .into_values()
                .collect(),
        };
        if self.linked_entries != expected {
            return Err(invalid(
                "paired product header has an inconsistent linked entry map",
            ));
        }
        Ok(())
    }

    pub fn to_canonical_bytes(&self) -> ArtifactResult<Vec<u8>> {
        self.validate()?;
        canonical_bytes(self)
    }

    pub fn from_canonical_bytes(bytes: &[u8]) -> ArtifactResult<Self> {
        let value: Self = decode_canonical(bytes)?;
        value.validate()?;
        Ok(value)
    }
}

/// External content-addressed join. Structural checks validate recipe/artifact
/// bytes and declarations, never whether a host linked or executed them.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativePairedArtifactManifest {
    pub schema_version: u16,
    pub binding: NativePairedBuildBinding,
    pub application_recipe: ProgramBuildRecipe,
    pub test_recipe: ProgramBuildRecipe,
    pub application_artifact: ProgramArtifactId,
    pub test_artifact: ProgramArtifactId,
}

impl NativePairedArtifactManifest {
    pub fn validate_declaration(&self) -> ArtifactResult<()> {
        self.binding.validate()?;
        if self.schema_version != NATIVE_PAIRED_TEST_SCHEMA_VERSION
            || self.application_artifact == self.test_artifact
        {
            return Err(invalid("invalid paired native artifact declaration"));
        }
        for recipe in [&self.application_recipe, &self.test_recipe] {
            recipe.validate()?;
            if recipe.program_revision != self.binding.program_revision
                || recipe.expected_artifact_id.is_some()
                || !matches!(&recipe.target.product,
                    ProgramProductMode::Native { product } if product.selected() == Some(&self.binding.selected_product))
            {
                return Err(invalid(
                    "paired recipes do not share the selected build binding",
                ));
            }
        }
        Ok(())
    }

    pub fn digest(&self) -> ArtifactResult<Digest> {
        self.validate_declaration()?;
        Ok(Digest::sha256(
            [
                b"runmat-native-paired-artifacts-v1\0".as_slice(),
                &canonical_bytes(self)?,
            ]
            .concat(),
        ))
    }

    pub fn validate_with_artifacts(
        &self,
        application: &ProgramArtifact,
        tests: &ProgramArtifact,
    ) -> ArtifactResult<()> {
        self.validate_declaration()?;
        if self.application_artifact != application.id
            || self.test_artifact != tests.id
            || application.form != ExecutableForm::NativeObjectV1
            || tests.form != ExecutableForm::NativeObjectV1
        {
            return Err(invalid(
                "paired native artifact identities or forms disagree",
            ));
        }
        application.validate_against(&self.application_recipe)?;
        tests.validate_against(&self.test_recipe)?;
        Ok(())
    }

    /// Compares declarations only. The linked receiver must extract these
    /// headers from the actual products and check its compiled entry map.
    pub fn validate_header_declarations(
        &self,
        application_header: &NativePairedProductHeader,
        test_header: &NativePairedProductHeader,
    ) -> ArtifactResult<()> {
        self.validate_declaration()?;
        application_header.validate()?;
        test_header.validate()?;
        if application_header.role != NativePairedProductRole::Application
            || test_header.role != NativePairedProductRole::Test
            || application_header.binding != self.binding
            || test_header.binding != self.binding
        {
            return Err(invalid(
                "paired embedded headers disagree with external manifest",
            ));
        }
        Ok(())
    }

    pub fn to_canonical_bytes(&self) -> ArtifactResult<Vec<u8>> {
        self.validate_declaration()?;
        canonical_bytes(self)
    }

    pub fn from_canonical_bytes(bytes: &[u8]) -> ArtifactResult<Self> {
        let value: Self = decode_canonical(bytes)?;
        value.validate_declaration()?;
        Ok(value)
    }
}

fn zero(value: Digest) -> bool {
    value.bytes().iter().all(|byte| *byte == 0)
}

fn invalid(message: &str) -> ArtifactError {
    ArtifactError::Invalid(message.into())
}
