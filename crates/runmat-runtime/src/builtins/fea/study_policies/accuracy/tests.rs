//! Each closed choice returns its typed value, keeps its catalog class, has a
//! catalog entry, and round-trips through the portable value codec.

use super::*;
use futures::executor::block_on;

macro_rules! assert_choice {
    ($function:ident, $name:literal, $class:expr, $decode:path, $expected:expr) => {{
        let value = block_on($function()).expect($name);
        assert_eq!($decode("test", &value).expect($name), $expected, $name);
        let Value::Object(object) = &value else {
            panic!("{} must return an object", $name)
        };
        assert_eq!(object.class_name().display_name(), $class, $name);
        let entry = runmat_builtins::builtin_catalog_entry_by_name($name).expect($name);
        assert!(entry
            .documentation
            .examples
            .iter()
            .all(|example| example.program.contains($name)));
        let encoded = crate::execution::value_codec::encode_inline_value(&value).expect($name);
        let decoded = crate::execution::value_codec::decode_inline_value(&encoded).expect($name);
        assert_eq!(decoded, value, $name);
    }};
}

