//! Named authored input bridge qualification, not full authored thermal-root admission.
//! Real imported functions execute inline before the canonical numerical solve. Process,
//! artifact-field, restart, and whole-root qualification are deliberately separate gates.
//! The checked document owns the named signals; the canonical fixture below explicitly wires
//! the source action and initial condition. This does not qualify authored source-action lowering.
