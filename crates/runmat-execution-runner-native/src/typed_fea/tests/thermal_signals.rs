const SOURCE: &str = r#"
import function heating from "./heating.m"
import function initialTemperature from "./initialTemperature.m"
geometry part {
    construct {
        feature body = box(width = 1 m, depth = 1 m, height = 1 m)
        result = feature.body
    }
}
mesh volume on geometry.part {
    tetrahedra {
        order = linear
        target_size = 0.2 m
        maximum_deviation = 0.01 m
    }
}
model heated {
    thermal { reference_temperature = 293.15 K }
    signal generation : heat_generation_density over time {
        generated by function.heating {
            arguments {}
            sample from 0 s to 1 s at 2 Hz
            interpolation = linear
            extrapolation = reject
            tolerance = 1e-12 W/m^3
        }
    }
    signal start : temperature over time {
        generated by function.initialTemperature {
            arguments {}
            sample from 0 s to 1 s at 2 Hz
            interpolation = linear
            extrapolation = reject
            tolerance = 1e-12 K
        }
    }
    initial warm {
        thermal.temperature {
            target = whole_model
            sample {
                signal = signal.start
                at = 0 s
                approach = right_limit
            }
        }
    }
}
study heating {
    geometry = geometry.part
    mesh = mesh.volume
    model = model.heated
    analysis heat {
        thermal transient {
            start_time = 0 s
            end_time = 1 s
            time_step = 0.5 s
            initial_conditions = [model.initial.warm]
        }
    }
}
"#;

// witness: FEA-THERMAL-INPUT-001/equivalence @ thermal_transient/tet4/public_study; coverage:
//   partial;
//   boundary: A linear-order transient with function-generated heating and initial temperature checks
//   and runs through the typed study path and matches tables and an independent
//   source/boundary energy; explicit and field-artifact variants are not compared here.
#[tokio::test]
async fn checked_named_thermal_inputs_match_tables_and_independent_source_boundary_energy() {
    let directory = tempfile::tempdir().unwrap();
    std::fs::create_dir_all(directory.path().join("src")).unwrap();
    std::fs::write(
        directory.path().join("runmat.toml"),
        "[package]\nname = \"named-thermal-inputs\"\n[sources]\nroots = [\"src\"]\n",
    )
    .unwrap();
    for (name, text) in [
        ("heating.m", "function y = heating(t)\narguments\n    t (:,1) double\nend\ny = t * 0 + 12;\nend\n"),
        ("initialTemperature.m", "function y = initialTemperature(t)\narguments\n    t (:,1) double\nend\ny = t * 2 + 300;\nend\n"),
        ("study.fea", SOURCE),
    ] { std::fs::write(directory.path().join("src").join(name), text).unwrap(); }
    let mut session = runmat_core::RunMatSession::with_options(false, false).unwrap();
    let project = runmat_package::build_frozen_project(
        &directory.path().join("runmat.toml"),
        std::collections::BTreeSet::new(),
    )
    .unwrap();
    session
        .install_project_handoff(runmat_package::FrozenProjectHandoff::new(project))
        .await
        .unwrap();
    let study_path = directory
        .path()
        .join("src/study.fea")
        .canonicalize()
        .unwrap();
    let checked = session
        .load_and_check_fea_source_path(&study_path)
        .await
        .unwrap();
    let report = checked.checked().check_result();
    assert_eq!(
        report.status,
        runmat_runtime::analysis::FeaCheckStatus::Valid,
        "checked thermal source diagnostics: {:?}",
        report.diagnostics
    );
    let ResolvedFeaRoot::Study(resolved) = checked
        .resolve_root(Some(&FeaRootSelector::Study {
            id: "heating".into(),
        }))
        .unwrap()
    else {
        panic!("expected a checked thermal study")
    };
    let authored = crate::typed_fea::preparation::prepare_study(
        &checked,
        resolved.clone(),
        &[],
        "thermal-test",
        &Default::default(),
    )
    .await;
    #[cfg(not(feature = "occt-native"))]
    {
        let error = authored.err().expect("exact geometry provider is required");
        assert!(
            error.contains("OCCT"),
            "unexpected preparation rejection: {error}"
        );
    }
    #[cfg(feature = "occt-native")]
    assert!(matches!(
        authored
            .expect("prepare standalone authored thermal study")
            .root
            .planning,
        crate::StudyRootPlanning::Thermal(_)
    ));
    let realized = resolved
        .study
        .realize_with_models(&resolved.models, &resolved.geometry, &[])
        .unwrap();
    let prepared = crate::typed_fea::input::prepare_input_materializations(&checked, &realized)
        .await
        .unwrap();
    let prepared = prepared
        .into_iter()
        .map(|plan| match plan {
            runmat_analysis_execution::InputMaterializationPlan::Ready(value) => *value,
            runmat_analysis_execution::InputMaterializationPlan::DeferredSignal(_) => {
                panic!("uniform inputs must not require mesh")
            }
        })
        .collect::<Vec<_>>();
    assert_eq!(prepared.len(), 2);
    // Cold transport has only one canonical Direct representation: descriptor
    // reconstruction. Retained per-chunk requests belong exclusively to Graph.
    let input = &prepared[0];
    let transport =
        crate::input_materialization_contract::InputMaterializationRequest::from_prepared(input)
            .unwrap();
    let wire = serde_json::to_value(&transport).unwrap();
    let reopened: crate::input_materialization_contract::InputMaterializationRequest =
        serde_json::from_value(wire.clone()).unwrap();
    assert_eq!(reopened.to_prepared().unwrap().program(), input.program());
    let mut altered = wire;
    altered.get_mut("signal").expect("original signal DTO")["invocations"] = serde_json::to_value(
        input
            .program()
            .chunks
            .iter()
            .map(|chunk| chunk.request.clone())
            .collect::<Vec<_>>(),
    )
    .unwrap();
    let altered: crate::input_materialization_contract::InputMaterializationRequest =
        serde_json::from_value(altered).unwrap();
    assert!(
        altered.to_prepared().is_err(),
        "Direct requests cannot override cold descriptor reconstruction"
    );
    let substitutions: [fn(&mut runmat_execution_artifact::ProgramExecutionRequest); 3] = [
        |request| {
            request.console = Some(runmat_execution::console::ConsoleLimits {
                max_records: 1,
                max_text_bytes: 16,
            })
        },
        |request| {
            request.environment = runmat_execution::EnvironmentSnapshot::new(vec![(
                "RUNMAT_PUBLIC_INPUT".into(),
                "different".into(),
            )])
            .unwrap()
        },
        |request| {
            request.job_id = Some(runmat_execution::JobId::derive(&[
                b"different-generator-job",
            ]))
        },
    ];
    for substitute in substitutions {
        let runmat_analysis_execution::PreparedInputMaterialization::Signal(mut changed) =
            (*input).clone()
        else {
            panic!("original signal")
        };
        let runmat_execution_artifact::WorkerProgramRequest::Direct(request) =
            &mut changed.program.chunks[0].request
        else {
            panic!("original Direct invocation")
        };
        substitute(request);
        request
            .validate_for_portable_host()
            .expect("individually valid invocation metadata");
        assert!(
            changed.validate().is_err(),
            "generator invocation must retain descriptor controls and unassigned state"
        );
    }
    let mut completed = Vec::new();
    for input in &prepared {
        let mut outputs = Vec::new();
        for chunk in &input.program().chunks {
            let request = chunk.direct_request().unwrap();
            let response = crate::execute_host_program_request(request.clone()).await;
            response.validate_against(request).unwrap();
            let ProgramExecutionResponse::Success {
                outputs: mut response_outputs,
            } = response
            else {
                panic!("named thermal function failed: {response:?}")
            };
            assert_eq!(response_outputs.len(), 1, "one original semantic output");
            let value = response_outputs.remove(0);
            outputs.push(GeneratorChunkOutput {
                chunk_identity: chunk.plan.identity,
                value,
            });
        }
        let chunks = input
            .program()
            .chunks
            .iter()
            .map(|chunk| chunk.plan.clone())
            .collect::<Vec<_>>();
        let foreign = prepared.iter().find(|other| other != &input).unwrap();
        let mut wrong = outputs.clone();
        wrong[0].chunk_identity = foreign.program().chunks[0].plan.identity;
        assert!(
            crate::input_materialization::materialize_input(input, &chunks, &wrong, None).is_err()
        );
        let (value, kind, identity, bytes) =
            crate::input_materialization::materialize_input(input, &chunks, &outputs, None)
                .unwrap();
        assert_eq!(kind, AnalysisNumericalObjectKind::Signal);
        let objects = prepare_analysis_objects(
            kind,
            identity,
            &bytes,
            DEFAULT_ANALYSIS_CHUNK_BYTES,
            ObjectNamespace::ResultValue,
            ObjectInventoryLimits::default(),
        )
        .unwrap();
        completed.push(
            crate::input_materialization::CompletedInputMaterialization {
                input: value,
                objects,
            },
        );
    }
    for order in [ElementOrder::Tet4, ElementOrder::Tet10] {
        let mesh = canonical_tetrahedron_solver_mesh(order);
        let mut generated = workload(realized.model.signals.clone(), &mesh);
        assert!(
            generated.execute(&mesh).is_err(),
            "unresolved generators cannot enter assembly"
        );
        crate::input_materialization::apply_to_model(&mut generated.model, completed.clone())
            .unwrap();
        let explicit = workload(vec![table(false), table(true)], &mesh);
        for (generated, explicit) in generated.model.signals.iter().zip(&explicit.model.signals) {
            assert_eq!(generated.signal_id(), explicit.signal_id());
            let provenance = match generated {
                PhysicalSignal::Temperature(signal) => &signal.provenance,
                PhysicalSignal::HeatGenerationDensity(signal) => &signal.provenance,
                _ => panic!("unexpected thermal input quantity"),
            };
            let SignalProvenance::Generated(provenance) = provenance else {
                panic!("named input lost generated provenance")
            };
            assert!(!provenance.callable_id.is_empty());
            assert!(!provenance.project_revision.is_empty());
            assert!(!provenance.frozen_input_digest.is_empty());
            assert_eq!(
                canonical_tabulated_signal_content_digest(generated).unwrap(),
                canonical_tabulated_signal_content_digest(explicit).unwrap()
            );
            assert_ne!(
                generated, explicit,
                "source provenance must remain distinct"
            );
        }
        assert_ne!(generated.identity().unwrap(), explicit.identity().unwrap());
        let actual = generated.execute(&mesh).unwrap();
        let reference = explicit.execute(&mesh).unwrap();
        actual.validate_complete().unwrap();
        assert_eq!(actual.time_points_s, reference.time_points_s);
        assert_eq!(actual.time_points_s, vec![0.0, 0.5, 1.0]);
        assert_eq!(actual.temperature_snapshots.len(), 3);
        assert_eq!(actual.temperature_gradient_snapshots.len(), 3);
        assert_eq!(actual.heat_flux_snapshots.len(), 3);
        assert_eq!(actual.ordered_node_ids.len(), mesh.topology.nodes.len());
        // Unit tetrahedron V=1/6; rho*c=2*3; q=12. Conservation gives dT/dt=2.
        for (index, (field, other)) in actual
            .temperature_snapshots
            .iter()
            .zip(&reference.temperature_snapshots)
            .enumerate()
        {
            assert_eq!(
                field.as_host_f64().unwrap().len(),
                mesh.topology.nodes.len()
            );
            for (&temperature, &explicit_temperature) in field
                .as_host_f64()
                .unwrap()
                .iter()
                .zip(other.as_host_f64().unwrap())
            {
                assert!((temperature - (300.0 + 2.0 * actual.time_points_s[index])).abs() < 1e-8);
                assert!((temperature - explicit_temperature).abs() < 1e-10);
            }
        }
        assert_eq!(
            actual.initial_state.applied_initial_condition_ids,
            vec!["warm"]
        );
        assert_eq!(actual.initial_state.reference_node_count, 0);
        for field in actual
            .temperature_gradient_snapshots
            .iter()
            .chain(&actual.heat_flux_snapshots)
        {
            assert_eq!(
                field.as_host_f64().unwrap().len(),
                mesh.topology.volume_elements.len() * 3
            );
            assert!(field
                .as_host_f64()
                .unwrap()
                .iter()
                .all(|value| value.abs() < 1e-8));
        }
        assert_eq!(actual.energy_balances.len(), 2);
        for (balance, other) in actual
            .energy_balances
            .iter()
            .zip(&reference.energy_balances)
        {
            balance.validate().unwrap();
            assert!(
                (balance.applied_power_w - runmat_types::physical::Quantity::new(2.0)).abs()
                    < runmat_types::physical::Quantity::new(1e-10)
            );
            assert!(
                (balance.storage_rate_w - runmat_types::physical::Quantity::new(2.0)).abs()
                    < runmat_types::physical::Quantity::new(1e-8)
            );
            assert!(balance.boundary_loss_w.abs() < runmat_types::physical::Quantity::new(1e-10));
            assert!(
                balance.prescribed_boundary_power_w.abs()
                    < runmat_types::physical::Quantity::new(1e-10)
            );
            assert!(balance.relative_residual <= 1e-8);
            assert!(
                (balance.applied_power_w - other.applied_power_w).abs()
                    < runmat_types::physical::Quantity::new(1e-10)
            );
        }
        for field in actual.energy_storage_rate_snapshots.iter().skip(1) {
            assert!(field
                .as_host_f64()
                .unwrap()
                .iter()
                .all(|value| (*value - 12.0).abs() < 1e-8));
        }
        // The same real compiled temperature history also drives a nonzero
        // prescribed boundary heat exchange, independently of volume generation.
        let boundary_generated = prescribed_boundary_workload(generated, &mesh);
        let boundary_explicit = prescribed_boundary_workload(explicit, &mesh);
        let boundary = boundary_generated.execute(&mesh).unwrap();
        let boundary_reference = boundary_explicit.execute(&mesh).unwrap();
        boundary.validate_complete().unwrap();
        assert_eq!(boundary.temperature_snapshots.len(), 3);
        for (index, (field, explicit_field)) in boundary
            .temperature_snapshots
            .iter()
            .zip(&boundary_reference.temperature_snapshots)
            .enumerate()
        {
            assert_eq!(
                field.as_host_f64().unwrap().len(),
                mesh.topology.nodes.len()
            );
            for (&value, &other) in field
                .as_host_f64()
                .unwrap()
                .iter()
                .zip(explicit_field.as_host_f64().unwrap())
            {
                assert!((value - (300.0 + 2.0 * boundary.time_points_s[index])).abs() < 1e-8);
                assert!((value - other).abs() < 1e-10);
            }
        }
        assert_eq!(boundary.energy_balances.len(), 2);
        for balance in &boundary.energy_balances {
            balance.validate().unwrap();
            assert!(balance.applied_power_w.abs() < runmat_types::physical::Quantity::new(1e-10));
            assert!(
                (balance.storage_rate_w - runmat_types::physical::Quantity::new(2.0)).abs()
                    < runmat_types::physical::Quantity::new(1e-8)
            );
            assert!(
                (balance.prescribed_boundary_power_w + runmat_types::physical::Quantity::new(2.0))
                    .abs()
                    < runmat_types::physical::Quantity::new(1e-8)
            );
            assert!(balance.boundary_loss_w.abs() < runmat_types::physical::Quantity::new(1e-10));
            assert!(balance.relative_residual <= 1e-8);
        }
    }
}

fn prescribed_boundary_workload(
    mut workload: ThermalWorkload,
    mesh: &runmat_meshing_core::SolverMeshArtifact,
) -> ThermalWorkload {
    workload.model.excitations.clear();
    workload.model.excitation_cases.clear();
    workload.model.boundaries.clear();
    workload.model.constraints = mesh
        .topology
        .boundary_faces
        .iter()
        .enumerate()
        .map(|(index, face)| {
            let target = face
                .provenance
                .iter()
                .find(|identity| identity.kind == runmat_meshing_core::PersistentEntityKind::Face)
                .expect("canonical face must retain its persistent source identity");
            AnalysisConstraint::Thermal(ThermalConstraint {
                constraint_id: format!("temperature_face_{index}"),
                kind: ThermalConstraintKind::Prescribed {
                    target: RegionTarget::boundary(
                        runmat_meshing_core::fixtures::fixture_boundary_selection(
                            &(target.source_topology_id.clone()),
                        ),
                    ),
                    value: PrescribedValue::Signal(SignalId("start".into())),
                },
            })
        })
        .collect();
    workload
}

fn workload(
    signals: Vec<PhysicalSignal>,
    mesh: &runmat_meshing_core::SolverMeshArtifact,
) -> ThermalWorkload {
    let mut model = fixture_model(FixtureId::CantileverLinearStatic);
    model.constraints.clear();
    model.boundaries.clear();
    // Explicit insulation keeps the canonical model's boundary-condition
    // admission intact without pinning temperature in the uniform-heating case.
    model.boundaries = mesh
        .topology
        .boundary_faces
        .iter()
        .enumerate()
        .map(|(index, face)| {
            let target = face
                .provenance
                .iter()
                .find(|identity| identity.kind == runmat_meshing_core::PersistentEntityKind::Face)
                .unwrap();
            AnalysisBoundary {
                boundary_id: format!("insulated_face_{index}"),
                target: RegionTarget::boundary(
                    runmat_meshing_core::fixtures::fixture_boundary_selection(
                        &(target.source_topology_id.clone()),
                    ),
                ),
                operator: BoundaryOperator::ThermalHeatFlux {
                    value: PrescribedValue::Constant(HeatFlux::new(0.0)),
                },
            }
        })
        .collect();
    model.signals = signals;
    model.materials[0].mass_density_kg_per_m3 = Some(runmat_types::physical::MassDensity::new(2.0));
    let thermal = model.materials[0].thermal.as_mut().unwrap();
    thermal.specific_heat_j_per_kgk = runmat_types::physical::SpecificHeat::new(3.0);
    thermal.conductivity_w_per_mk = runmat_types::physical::ThermalConductivity::new(1.0);
    model.thermal = Some(ThermalDomain {
        reference_temperature: Temperature::new(293.15),
    });
    model.initial_conditions = vec![InitialCondition::Temperature(InitialConditionValue {
        initial_condition_id: "warm".into(),
        target: InitialConditionTarget::WholeModel,
        frame: CoordinateFrame::Global,
        value: InitialValue::SignalSample {
            signal_id: SignalId("start".into()),
            abscissa: 0.0,
            approach: SignalSampleApproach::RightLimit,
        },
        applies_before_step_id: "heat".into(),
    })];
    model.excitations = vec![ExcitationAction::HeatGeneration(AnalysisExcitation {
        excitation_id: ExcitationId("generation".into()),
        target: ExcitationTarget::WholeModel,
        frame: CoordinateFrame::Global,
        direction: None,
        distribution: ExcitationDistribution::IntensityPerVolume,
        kinematics: ExcitationKinematics::FixedFrame,
        signal_id: SignalId("generation".into()),
        active_step_ids: vec!["heat".into()],
        combination_group: None,
        projection: ProjectionRequirement {
            preserve_resultant: true,
            preserve_moment: false,
            relative_tolerance: 1e-12,
        },
    })];
    model.excitation_cases = vec![ExcitationCase {
        case_id: ExcitationCaseId("heating".into()),
        action_ids: vec![ExcitationId("generation".into())],
        activation: ExcitationCaseActivation::Always,
    }];
    let mut step = ProcedureStep::thermal_transient("heat");
    step.independent_domain = IndependentDomain::TimeSeconds {
        origin: 0.0,
        start: 0.0,
        end: 1.0,
        interval_count: 2,
    };
    model.sequence = AnalysisSequence::from_steps("heating", vec![step]);
    ThermalWorkload {
        initial_fields: Vec::new(),
        model,
        step_id: ProcedureStepId("heat".into()),
        backend: ComputeBackend::Cpu,
        procedure: ThermalProcedureControl::BackwardEuler { snapshot_count: 3 },
        residual_target: 1e-10,
    }
}

fn table(initial: bool) -> PhysicalSignal {
    macro_rules! typed {
        ($kind:ident, $quantity:ident, $value:expr, $id:expr) => {
            PhysicalSignal::$kind(Signal {
                signal_id: SignalId($id.into()),
                shape: SignalShape::Scalar,
                frame: None,
                representation: SignalRepresentation::Tabulated(TabulatedSignal {
                    domain: TabulatedSignalDomain::TimeSeconds,
                    knots: [0.0, 0.5, 1.0]
                        .into_iter()
                        .map(|time| {
                            SignalKnot::continuous(
                                time,
                                SignalOrdinate::Real(SignalValue::Scalar($quantity::new(
                                    $value + if initial { 2.0 * time } else { 0.0 },
                                ))),
                            )
                        })
                        .collect(),
                    interpolation: SignalInterpolation::Linear,
                    extrapolation: SignalExtrapolation::Reject,
                }),
                precision: SignalPrecision::Real64,
                evidence: SignalApproximationEvidence {
                    max_absolute_error: None,
                    max_relative_error: None,
                    derivative_max_absolute_error: None,
                    sample_count: 3,
                },
                provenance: SignalProvenance::Authored,
            })
        };
    }
    if initial {
        typed!(Temperature, Temperature, 300.0, "start")
    } else {
        typed!(
            HeatGenerationDensity,
            HeatGenerationDensity,
            12.0,
            "generation"
        )
    }
}
