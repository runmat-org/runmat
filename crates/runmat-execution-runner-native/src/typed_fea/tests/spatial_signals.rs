//! Authored deferred-input authority through source preparation and actual CAD meshing.
//! This deliberately rejects a named generator with the wrong row shape. The callable API does
//! not yet supply mesh cardinality or coordinates to generators, so this is not qualification of
//! a dynamically mesh-sized generator or a numerical structural solve.

use runmat_analysis_core::{
    AuthoredSignalFieldLocation, AuthoredSignalTopologySelector, SignalShape,
};
use runmat_analysis_execution::InputMaterializationPlan;
use runmat_runtime::analysis::{FeaCheckStatus, FeaRootSelector, ResolvedFeaRoot};

const SOURCE: &str = r#"
import function density from "./density.m"
geometry part {
    construct {
        feature body = box(width = 1 m, depth = 0.5 m, height = 0.25 m)
        result = feature.body
    }
}
mesh volume on geometry.part {
    tetrahedra {
        order = linear
        target_size = 0.25 m
        maximum_deviation = 0.01 m
    }
}
model structure {
    signal drive : body_force_density over time {
        topology = study_solver_mesh
        location = node
        components = 3
        frame = global
        generated by function.density {
            arguments {}
            sample_points = [0 s, 1 s]
            interpolation = linear
            extrapolation = reject
        }
    }
    excitation density {
        body_force {
            target = whole_model
            signal = signal.drive
        }
    }
    load_case forcing { include excitation.density }
}
study static {
    geometry = geometry.part
    mesh = mesh.volume
    model = model.structure
    analysis solve { structural static {} }
}
"#;

#[tokio::test]
async fn authored_named_spatial_input_retains_deferred_authority_until_actual_mesh() {
    let directory = tempfile::tempdir().unwrap();
    std::fs::create_dir_all(directory.path().join("src")).unwrap();
    std::fs::write(
        directory.path().join("runmat.toml"),
        "[package]\nname = \"authored-spatial-input\"\n[sources]\nroots = [\"src\"]\n",
    )
    .unwrap();
    // A valid pure named callable, but only one spatial row. Preparation must not execute it
    // or guess that one row is the study's topology cardinality.
    std::fs::write(
        directory.path().join("src/density.m"),
        "function y = density(t)\narguments\n    t (:,1) double\nend\ny = reshape(t * [2, 3, 5], numel(t), 1, 3);\nend\n",
    )
    .unwrap();
    let study_path = directory.path().join("src/study.fea");
    std::fs::write(&study_path, SOURCE).unwrap();
    let mut session = runmat_core::RunMatSession::with_options(false, false).unwrap();
    let project = runmat_package::build_frozen_project(
        &directory.path().join("runmat.toml"),
        std::collections::BTreeSet::new(),
    )
    .unwrap();
    session
        .install_project_handoff(runmat_package::FrozenProjectHandoff::new(project))
        .await
        .unwrap();
    let checked = session
        .load_and_check_fea_source_path(&study_path.canonicalize().unwrap())
        .await
        .unwrap();
    let report = checked.checked().check_result();
    assert_eq!(
        report.status,
        FeaCheckStatus::Valid,
        "{:?}",
        report.diagnostics
    );
    let ResolvedFeaRoot::Study(resolved) = checked
        .resolve_root(Some(&FeaRootSelector::Study {
            id: "static".into(),
        }))
        .unwrap()
    else {
        panic!("expected a checked structural study")
    };
    let realized = resolved
        .study
        .realize_with_models(&resolved.models, &resolved.geometry, &[])
        .unwrap();
    let plans = crate::typed_fea::input::prepare_input_materializations(&checked, &realized)
        .await
        .unwrap();
    let [InputMaterializationPlan::DeferredSignal(frozen)] = plans.as_slice() else {
        panic!("authored spatial input must remain deferred before mesh")
    };
    assert_eq!(frozen.authored(), &realized.model.signals[0]);
    assert_eq!(
        frozen.authored().shape(),
        &SignalShape::DeferredTopologyField {
            selector: AuthoredSignalTopologySelector::StudySolverMesh {
                location: AuthoredSignalFieldLocation::Node,
            },
            component_count: 3,
        }
    );
    assert!(frozen
        .authored()
        .shape()
        .realized_component_count(None)
        .is_none());
    let retained = plans[0].expectation().unwrap();
    let reopened: runmat_analysis_execution::InputMaterializationPlanExpectation =
        serde_json::from_slice(&serde_json::to_vec(&retained).unwrap()).unwrap();
    assert_eq!(retained, reopened);
    let frozen_identity = frozen.identity().unwrap();
    let prepared = crate::typed_fea::preparation::prepare_study(
        &checked,
        resolved,
        &[],
        "authored-spatial-input-test",
        &Default::default(),
    )
    .await;
    #[cfg(not(feature = "occt-native"))]
    {
        let error = prepared.err().expect("exact geometry requires OCCT");
        assert!(error.contains("OCCT"), "{error}");
    }
    #[cfg(feature = "occt-native")]
    {
        let prepared = prepared.unwrap();
        assert!(prepared.root.planning.structural().is_some());
        let root = crate::prepare_structural_study_root(prepared.root).unwrap();
        assert_eq!(root.result_expectation().study, realized);
        assert_eq!(
            root.result_expectation().input_materializations,
            vec![retained.clone()]
        );
        let inventory = runmat_execution_artifact::object::ObjectInventoryLimits::default();
        let mut store = crate::FilesystemObjectStore::open(
            directory.path().join("objects"),
            inventory.max_object_bytes,
        )
        .unwrap();
        root.write_to(&mut store).unwrap();
        let decoded = crate::decode_structural_study_root(root.request(), &store).unwrap();
        assert_eq!(decoded.study, realized);
        assert_eq!(decoded.input_materializations, plans);
        let geometry =
            crate::decode_geometry_meshing_root(&decoded.geometry_meshing, &store).unwrap();
        let response = crate::execute_geometry_materialization_program_request(
            &geometry.geometry,
            &mut store,
            crate::NativeGeometryMaterializationLimits { inventory },
        );
        let runmat_execution_artifact::ProgramExecutionResponse::ExternalizedSuccess {
            outputs,
            ..
        } = response
        else {
            panic!("authored exact geometry failed: {response:?}")
        };
        let [runmat_execution::value::ValuePayload::Object(output_root)] = outputs.as_slice()
        else {
            panic!("geometry output must be a single immutable object")
        };
        let output = runmat_analysis_execution::import_geometry_materialization_output(
            &store,
            output_root,
            &decoded.artifact_access,
        )
        .unwrap();
        output
            .validate_against(&root.result_expectation().geometry_request)
            .unwrap();
        let exact = runmat_meshing_execution::import_exact_geometry_input(
            &store,
            output.document.clone(),
            &output.geometry_root,
            decoded.artifact_access.clone(),
            inventory,
        )
        .unwrap();
        let mut request = geometry.request.meshing_request;
        request.tolerance = output.document.tolerance;
        let kernel = crate::native_meshing_kernel_dispatcher();
        let mut progress = runmat_meshing_execution::NoopMeshingProgress;
        let mut executor = runmat_meshing_execution::SerialExactMeshingExecutor {
            store: &mut store,
            kernel: &kernel,
            cancellation: &runmat_meshing_core::NeverCancelled,
            progress: &mut progress,
            chunk_policy: runmat_meshing_core::MeshingChunkPolicy {
                maximum_chunk_bytes: 1024 * 1024,
                maximum_records_per_chunk: 4096,
                maximum_total_encoded_bytes: 128 * 1024 * 1024,
            },
            inventory_limits: inventory,
        };
        let meshing = runmat_meshing_execution::execute_exact_meshing_dag(
            runmat_meshing_execution::ExactMeshingDagRun {
                geometry: &exact,
                ceilings: runmat_meshing_core::MeshingExecutionCeilings::PORTABLE_DEFAULT,
                request,
                artifact_access: decoded.artifact_access.clone(),
                capability_cohort: Some(output.platform.capability_cohort.clone()),
                program_revision: root.request().recipe.program_revision.clone(),
                preferred_edges_per_partition: geometry.request.preferred_edges_per_partition,
                preferred_faces_per_partition: geometry.request.preferred_faces_per_partition,
                inventory_limits: inventory,
                evidence: runmat_meshing_execution::MeshingRunEvidenceContext {
                    platform: output.platform,
                    sizing: Vec::new(),
                    cache_admission: runmat_meshing_core::CacheAdmissionDecision::Admitted,
                },
                named_regions: Default::default(),
            },
            &mut executor,
        )
        .unwrap();
        meshing.evidence.validate(&meshing.artifact).unwrap();
        assert!(meshing.artifact.topology.nodes.len() > 1);
        let resolved = decoded.input_materializations[0]
            .resolve(&meshing.artifact)
            .unwrap();
        assert_eq!(
            resolved.expectation().unwrap(),
            reopened.resolve(&meshing.artifact).unwrap()
        );
        assert_eq!(
            decoded.input_materializations[0].expectation().unwrap(),
            retained
        );
        assert_eq!(frozen.identity().unwrap(), frozen_identity);
        let runmat_analysis_execution::PreparedInputMaterialization::Signal(signal) = &resolved
        else {
            panic!("resolved body density must be a signal")
        };
        assert_eq!(
            signal.admitted.generator_identity,
            frozen.admitted().generator_identity
        );
        assert_ne!(
            signal.admitted.materialization_identity,
            frozen.admitted().materialization_identity
        );
        assert_eq!(
            signal.topology_binding.as_ref().unwrap().entity_count(),
            meshing.artifact.topology.nodes.len()
        );
        let mut outputs = Vec::new();
        for chunk in &resolved.program().chunks {
            let request = chunk.direct_request().unwrap();
            let response = crate::execute_host_program_request(request.clone()).await;
            response.validate_against(request).unwrap();
            let runmat_execution_artifact::ProgramExecutionResponse::Success { outputs: values } =
                response
            else {
                panic!("named density callable failed: {response:?}")
            };
            let [value] = <[_; 1]>::try_from(values).expect("one generator output");
            outputs.push(runmat_analysis_execution::GeneratorChunkOutput {
                chunk_identity: chunk.plan.identity,
                value,
            });
        }
        let chunks = resolved
            .program()
            .chunks
            .iter()
            .map(|chunk| chunk.plan.clone())
            .collect::<Vec<_>>();
        assert!(crate::input_materialization::materialize_input(
            &resolved, &chunks, &outputs, None
        )
        .is_err());
        assert!(
            crate::input_materialization::materialize_input(
                &resolved,
                &chunks,
                &outputs,
                Some(&meshing.artifact)
            )
            .is_err(),
            "one-row generator must not be broadcast over actual solver nodes"
        );
    }
    #[cfg(not(feature = "occt-native"))]
    assert_eq!(frozen.identity().unwrap(), frozen_identity);
}
