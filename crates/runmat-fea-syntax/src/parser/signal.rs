use super::FeaParser;
use crate::lexical::FeaTokenKind;
use crate::syntax::{FeaBlock, FeaStatementKind, FeaTokenRange};
use crate::{FeaSyntaxDiagnostic, FeaSyntaxDiagnosticKind};

impl FeaParser {
    pub(super) fn parse_uniform_sample(
        &mut self,
        significant: &[usize],
        range: FeaTokenRange,
    ) -> FeaStatementKind {
        let from = significant
            .iter()
            .position(|index| self.lexeme(*index) == "from");
        let to = significant
            .iter()
            .position(|index| self.lexeme(*index) == "to");
        let at = significant
            .iter()
            .position(|index| self.lexeme(*index) == "at");
        let valid = matches!((from, to, at), (Some(1), Some(to), Some(at)) if to > 2 && at > to + 1 && at + 1 < significant.len());
        if !valid {
            self.diagnostics.push(FeaSyntaxDiagnostic {
                kind: FeaSyntaxDiagnosticKind::ExpectedToken,
                span: range.span,
                message: "sampling requires `sample from <start> to <end> at <rate>`".into(),
            });
        }
        let from = from.unwrap_or(1);
        let to = to.unwrap_or(significant.len());
        let at = at.unwrap_or(significant.len());
        FeaStatementKind::UniformSample {
            start: self.parse_expression_indices(
                significant.get(from + 1..to).unwrap_or_default(),
                range.span,
            ),
            end: self.parse_expression_indices(
                significant.get(to + 1..at).unwrap_or_default(),
                range.span,
            ),
            rate: self.parse_expression_indices(
                significant.get(at + 1..).unwrap_or_default(),
                range.span,
            ),
        }
    }

    pub(super) fn parse_signal_definition(
        &mut self,
        significant: &[usize],
        body: FeaBlock,
    ) -> Option<FeaStatementKind> {
        let valid = significant.len() == 6
            && self.kind(significant[2]) == Some(FeaTokenKind::Colon)
            && self.lexeme(significant[4]) == "over";
        if !valid {
            self.diagnostics.push(FeaSyntaxDiagnostic {
                kind: FeaSyntaxDiagnosticKind::ExpectedToken,
                span: self.token(significant[0]).span,
                message: "signal header requires `signal <name> : <quantity> over <domain>`"
                    .to_string(),
            });
        }
        let fallback = significant[0];
        let name = self.name(
            *significant.get(1).unwrap_or(&fallback),
            FeaSyntaxDiagnosticKind::ExpectedIdentifier,
        )?;
        let quantity = self.name(
            *significant.get(3).unwrap_or(&fallback),
            FeaSyntaxDiagnosticKind::ExpectedIdentifier,
        )?;
        let domain = self.name(
            *significant.get(5).unwrap_or(&fallback),
            FeaSyntaxDiagnosticKind::ExpectedIdentifier,
        )?;
        Some(FeaStatementKind::SignalDefinition {
            name,
            quantity,
            domain,
            body,
        })
    }

    pub(super) fn parse_generated_function(
        &mut self,
        start: usize,
        open: usize,
        body: FeaBlock,
    ) -> Option<FeaStatementKind> {
        let significant = self.significant(start, open);
        if significant.len() < 4
            || self.lexeme(significant[0]) != "generated"
            || self.lexeme(significant[1]) != "by"
        {
            return None;
        }
        let function = self.parse_reference_indices(&significant[2..])?;
        if function.segments.first().map(|name| name.text.as_str()) != Some("function")
            || function.segments.len() != 2
        {
            self.diagnostics.push(FeaSyntaxDiagnostic {
                kind: FeaSyntaxDiagnosticKind::ExpectedToken,
                span: function.span,
                message: "generator requires `generated by function.<imported_name>`".into(),
            });
        }
        Some(FeaStatementKind::GeneratedByFunction { function, body })
    }
}
