use crate::lexical::FeaTokenKind;
use serde::{Deserialize, Serialize};

/// The kind of a node in the lossless syntax tree.
///
/// Node kinds are generic: they name the shape of the syntax (a declaration, a block, a value
/// statement, a call), never a domain word. Which words head a declaration or a statement in a
/// given file kind is the dialect registry's business ([`crate::dialect`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum NodeKind {
    /// The whole file. Holds every byte, trailing trivia and the end-of-file token included.
    SourceFile,
    /// Syntax the parser could not place; its tokens are kept verbatim.
    Error,

    // ---------------------------------------------------------------- file-level forms
    /// `runmat 0.7`: the language version header.
    LanguageHeader,
    /// `std 1`: the vocabulary version header.
    StdHeader,
    /// `import <kind> <name> from "<path>"`.
    Import,
    /// `use <kind> <name> from "<path>" [@ "<pin>"] [as <alias>] [{ overrides }]`, or
    /// `use "<folder>" [as <alias>]`, or `use <folder.path>`.
    UseDeclaration,
    /// `<word> <name> <header…> { … }` at file level.
    Declaration,
    /// The tokens between a declaration's (or block statement's) name and its `{`.
    Header,
    /// `{ … }` holding statements.
    Block,

    // ---------------------------------------------------------------- generic statements
    /// `let | input | property | <registry word> <name> [: <type>] [= <value>]`.
    ValueStatement,
    /// `<path> (= | <= | >=) <value>`.
    Assignment,
    /// `constrain <expr> [= <expr>]`.
    Constrain,
    /// `when <condition> { … }`.
    When,
    /// `publish <name> [= <value>]`.
    Publish,
    /// `check <name> [= <value>]` or `check <name> { … }`.
    Check,
    /// `link <kind> <from> to <target>`.
    Link,
    /// `solved { … }`: a cache the solver rewrites.
    Solved,
    /// `<words…> [name] { … }`: a nested block headed by registry words.
    BlockStatement,
    /// A statement the dialect gives no shape: its tokens are kept verbatim.
    Command,

    // ---------------------------------------------------------------- `.fea` statement shapes
    // These are the `.fea` dialect's current statement forms. They move to the generic forms
    // above in the `.fea` semantic migration (M1+), owned by the FEA effort.
    /// `generated by function.<name> { … }`.
    GeneratedBy,
    /// `sample from <start> to <end> at <rate>`.
    UniformSample,
    /// `<kind> on <target> = <value>`.
    AppliedLoad,
    /// `signal <name> : <quantity> over <domain> { … }`.
    SignalDefinition,
    /// `<model keyword> <name> { … }`.
    ModelDefinition,
    /// `output <name> { … }`.
    OutputDefinition,
    /// `output <name> = <value>`.
    Output,
    /// `assign <property> to <target>`.
    PropertyAssignment,
    /// `set <path> = <value>`.
    SourceParameterUpdate,
    /// `use <path>` (the `.fea` property use).
    PropertyUse,
    /// `require <path> = <value>`.
    Requirement,
    /// `feature <name> = <value>`.
    Feature,
    /// `include <value>`.
    Include,
    /// `retain <value>`.
    Retain,

    // ---------------------------------------------------------------- pieces
    /// One name token in a declaring position.
    Name,
    /// A dotted path in a target position (`input.width`, `source.parameter.x`).
    Path,
    /// Type syntax after `:` (`length`, `region<solid>`), kept as tokens.
    Type,
    /// Unit syntax after a number (`mm`, `kg/m^3`), kept as tokens.
    Unit,
    /// A version or pin literal (`0.7`, `1`).
    Version,

    // ---------------------------------------------------------------- expressions
    NumberLiteral,
    StringLiteral,
    /// `a.b.c` in a value position.
    Reference,
    /// `[a, b]`.
    List,
    /// `{ a = 1, b = 2 }`.
    Record,
    /// `a = 1` in a record.
    RecordEntry,
    /// `( … )`.
    Group,
    /// `-x`, `+x`.
    Unary,
    /// `a + b`, `a .. b`, `a < b`.
    Binary,
    /// `f(…)`.
    Call,
    /// `name = value` in a call.
    NamedArgument,
    /// `f x`: a word applied to the expression after it (`select name "Beam"`).
    PrefixApplication,
    /// `5 mm`.
    Quantity,
    /// `a ± t`.
    Toleranced,
    /// `a as <unit>`.
    Coerce,
    /// `<reference> @ "<pin>"`.
    Pinned,
}

impl NodeKind {
    /// Nesting rank for nodes recorded over the same tokens: the lower rank encloses.
    pub(crate) fn rank(self) -> u8 {
        use NodeKind::*;
        match self {
            SourceFile => 0,
            Error => 1,
            LanguageHeader | StdHeader | Import | UseDeclaration | Declaration => 2,
            Block => 3,
            ValueStatement
            | Assignment
            | Constrain
            | When
            | Publish
            | Check
            | Link
            | Solved
            | BlockStatement
            | Command
            | GeneratedBy
            | UniformSample
            | AppliedLoad
            | SignalDefinition
            | ModelDefinition
            | OutputDefinition
            | Output
            | PropertyAssignment
            | SourceParameterUpdate
            | PropertyUse
            | Requirement
            | Feature
            | Include
            | Retain => 4,
            Header => 5,
            RecordEntry | NamedArgument => 6,
            Pinned | Coerce | Toleranced | Quantity | PrefixApplication | Call | Binary | Unary
            | Group | Record | List => 7,
            Reference => 8,
            Path => 9,
            Type | Unit | Version => 10,
            NumberLiteral | StringLiteral => 11,
            Name => 12,
        }
    }

    pub fn is_statement(self) -> bool {
        self.rank() == 4
    }

    pub fn is_expression(self) -> bool {
        matches!(self.rank(), 7 | 8 | 11)
    }
}

/// A leaf's kind: the lexer's token kind, trivia included.
pub type TokenKind = FeaTokenKind;
