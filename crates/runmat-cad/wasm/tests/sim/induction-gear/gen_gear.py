# Writes gear.part beside it (python3 gen_gear.py gear.part): a 24-tooth spur gear (module 4) in
# a single-turn induction-hardening coil, and the air round both.
import math, sys
Z = 24
m = 4.0
r_root, r_pitch, r_tip = m * (Z / 2 - 1.25), m * Z / 2, m * (Z / 2 + 1)   # 43, 48, 52 mm
pitch_angle = 2 * math.pi / Z
# Half the tooth's angular width at the root, the pitch circle and the tip: straight flanks in
# two segments, close to the involute's shape at this size.
half = {r_root: 0.30 * pitch_angle, r_pitch: 0.25 * pitch_angle, r_tip: 0.155 * pitch_angle}
f = lambda p: f"[{p[0]:.4f} mm, {p[1]:.4f} mm]"
pol = lambda r, a: (r * math.cos(a), r * math.sin(a))
lines = []
for k in range(Z):
    c = k * pitch_angle
    pts = [pol(r_root, c - half[r_root]), pol(r_pitch, c - half[r_pitch]), pol(r_tip, c - half[r_tip]),
           pol(r_tip, c + half[r_tip]), pol(r_pitch, c + half[r_pitch]), pol(r_root, c + half[r_root]),
           pol(r_root, (k + 1) * pitch_angle - half[r_root])]
    for i, name in enumerate(["fa", "fb", "tip", "fc", "fd", "root"]):
        lines.append(f"        t{k}_{name} = line(start = {f(pts[i])}, end = {f(pts[i + 1])})")
teeth = "\n".join(lines)

# The coil: a rectangular copper ring, 6 mm radially, round the gear with a 4 mm coupling gap,
# split at +x where its two leads run out to the edge of the air.
gap, radial, lead_w, slot = 4.0, 6.0, 6.0, 6.0
ri, ro = r_tip + gap, r_tip + gap + radial
edge = 150.0
yi, yo = slot / 2, slot / 2 + lead_w
xi, xo = math.sqrt(ri * ri - yi * yi), math.sqrt(ro * ro - yo * yo)
coil = "\n".join([
    f"        lead_in_top = line(start = [{edge:.4f} mm, {yo:.4f} mm], end = [{xo:.4f} mm, {yo:.4f} mm])",
    f"        outer = arc(center = [0 mm, 0 mm], start = [{xo:.4f} mm, {yo:.4f} mm], end = [{xo:.4f} mm, {-yo:.4f} mm])",
    f"        lead_out_bottom = line(start = [{xo:.4f} mm, {-yo:.4f} mm], end = [{edge:.4f} mm, {-yo:.4f} mm])",
    f"        lead_out_end = line(start = [{edge:.4f} mm, {-yo:.4f} mm], end = [{edge:.4f} mm, {-yi:.4f} mm])",
    f"        lead_out_top = line(start = [{edge:.4f} mm, {-yi:.4f} mm], end = [{xi:.4f} mm, {-yi:.4f} mm])",
    f"        inner = arc(center = [0 mm, 0 mm], start = [{xi:.4f} mm, {yi:.4f} mm], end = [{xi:.4f} mm, {-yi:.4f} mm])",
    f"        lead_in_bottom = line(start = [{xi:.4f} mm, {yi:.4f} mm], end = [{edge:.4f} mm, {yi:.4f} mm])",
    f"        lead_in_end = line(start = [{edge:.4f} mm, {yi:.4f} mm], end = [{edge:.4f} mm, {yo:.4f} mm])",
])

text = f'''runmat 0.7
std 1

// A spur gear in its induction-hardening coil: a 24-tooth, module 4 gear in 42CrMo4 steel
// ({2 * r_tip:.0f} mm over the tips, 20 mm face, 30 mm bore) inside a single-turn water-cooled copper
// coil, 6 x 10 mm in section, {gap:.0f} mm clear of the tips. The coil's two leads run out along +x
// to the edge of the air, a 300 x 300 x 200 mm box round both, so the current enters and leaves
// the study through the leads' ends ("Coil in", "Coil out").
// Hand check: at 10 kHz the current's skin depth in the steel below its Curie point is
// sqrt(2 rho / (omega mu)) = 0.16 mm (rho 2.2e-7 Ohm m, mu_r 100); above it, mu_r 1, 2.6 mm.
// Generated by gen_gear.py (tooth count, module and coil sizes); edit there and re-run it.
part gear {{
    input face_width : length = 20 mm
    input bore : length = 30 mm
    input coil_height : length = 10 mm
    input air_below : length = 90 mm
    input air_height : length = 200 mm

    sketch gear_s on origin.xy {{
{teeth}
        bore = circle(center = [0 mm, 0 mm], radius = input.bore / 2)
    }}
    feature gear = extrude(profile = sketch.gear_s, distance = input.face_width)

    feature coil_plane = plane.offset(base = origin.xy, distance = (input.face_width - input.coil_height) / 2)
    sketch coil_s on plane.coil_plane {{
{coil}
    }}
    feature coil = extrude(profile = sketch.coil_s, distance = input.coil_height)

    feature air_plane = plane.offset(base = origin.xy, distance = -input.air_below)
    sketch air_s on plane.air_plane {{
        front = line(start = [-{edge:.0f} mm, -{edge:.0f} mm], end = [{edge:.0f} mm, -{edge:.0f} mm])
        right = line(start = [{edge:.0f} mm, -{edge:.0f} mm], end = [{edge:.0f} mm, {edge:.0f} mm])
        back = line(start = [{edge:.0f} mm, {edge:.0f} mm], end = [-{edge:.0f} mm, {edge:.0f} mm])
        left = line(start = [-{edge:.0f} mm, {edge:.0f} mm], end = [-{edge:.0f} mm, -{edge:.0f} mm])
    }}
    feature air = extrude(profile = sketch.air_s, distance = input.air_height)
    feature surround = boolean.subtract(target = feature.air.body, tools = [feature.gear.body, feature.coil.body], keep_tools = true)

    region coil_in : face = {{ select = [feature.coil.face.side(coil_s.lead_in_end)], expect = exactly_one, body = feature.coil.body, label = "Coil in" }}
    region coil_out : face = {{ select = [feature.coil.face.side(coil_s.lead_out_end)], expect = exactly_one, body = feature.coil.body, label = "Coil out" }}
    region outer_boundary : face = {{
        select = [
            feature.air.face.start,
            feature.air.face.end,
            feature.air.face.side(air_s.front),
            feature.air.face.side(air_s.right),
            feature.air.face.side(air_s.back),
            feature.air.face.side(air_s.left)
        ],
        expect = at_least_one,
        body = feature.air.body,
        label = "Outer boundary"
    }}

    output gear = {{ body = feature.gear.body, label = "Gear", part_number = "SG-M4-24", material = "steel_42crmo4", color = "#9AA3AD" }}
    output coil = {{ body = feature.coil.body, label = "Coil", material = "copper_c11000", color = "#C8794A" }}
    output air = {{ body = feature.air.body, label = "Air", color = "#CFE3F5" }}
}}
'''
open(sys.argv[1] if len(sys.argv) > 1 else "gear.part", "w").write(text)
