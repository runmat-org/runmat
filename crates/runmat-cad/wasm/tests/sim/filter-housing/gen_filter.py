# Writes filter.part beside it (python3 gen_filter.py filter.part): a hydraulic return-line
# filter's oil and its pleated cartridge, 24 pleats of 1.5 mm media from 22 to 45 mm radius.
import math, sys
N, r_o, r_i, t = 24, 45.0, 22.0, 1.5
# The pleat's center line: a closed zigzag between the two radii.
center = []
for k in range(N):
    a = 2 * math.pi * k / N
    center.append((r_o * math.cos(a), r_o * math.sin(a)))
    b = a + math.pi / N
    center.append((r_i * math.cos(b), r_i * math.sin(b)))

def offset(points, d):
    """The closed polyline offset by d to its left, with mitred corners."""
    n = len(points)
    out = []
    for i in range(n):
        p0, p1, p2 = points[i - 1], points[i], points[(i + 1) % n]
        def normal(a, b):
            dx, dy = b[0] - a[0], b[1] - a[1]
            l = math.hypot(dx, dy)
            return (-dy / l, dx / l)
        n1, n2 = normal(p0, p1), normal(p1, p2)
        bx, by = n1[0] + n2[0], n1[1] + n2[1]
        bl = math.hypot(bx, by)
        bx, by = bx / bl, by / bl
        s = d / (bx * n1[0] + by * n1[1])
        out.append((p1[0] + bx * s, p1[1] + by * s))
    return out

# The zigzag runs anticlockwise, so its left is inward.
inner, outer = offset(center, t / 2), offset(center, -t / 2)
f = lambda p: f"[{p[0]:.4f} mm, {p[1]:.4f} mm]"
def loop(name, pts):
    return "\n".join(f"        {name}{i} = line(start = {f(pts[i])}, end = {f(pts[(i + 1) % len(pts)])})" for i in range(len(pts)))
upstream = [f"            feature.media.face.side(media_s.o{i})" for i in range(len(outer))]
area = 2 * N * math.hypot(r_o - r_i * math.cos(math.pi / N), r_i * math.sin(math.pi / N)) * 150e-3 / 1e3
text = f'''runmat 0.7
std 1

// The oil in a hydraulic return-line filter and its pleated cartridge. The bowl is 120 mm
// across and 150 mm tall inside; the oil comes in through a 20 mm side port near the top,
// passes in through the pleated media ("Media", a porous body, {N} pleats of {t} mm media from
// {r_i:.0f} to {r_o:.0f} mm radius over the bowl's full height, sealed at both ends by the bowl), and
// leaves down the cartridge's core through a 20 mm port in the floor.
// Laminar sizing at 20 L/min of ISO VG 46 oil at 40 degC (46 cSt): 1.06 m/s in the 20 mm
// ports, Re = 461. The media's {area:.3f} m^2 sees 2.0 mm/s.
// Generated by gen_filter.py (pleat count, radii and media thickness); edit there and re-run it.
part filter {{
    input bowl : length = 120 mm
    input height : length = 150 mm
    input port : length = 20 mm
    input port_height : length = 120 mm
    input port_length : length = 40 mm

    sketch bowl_s on origin.xy {{
        wall = circle(center = [0 mm, 0 mm], radius = input.bowl / 2)
    }}
    feature bowl = extrude(profile = sketch.bowl_s, distance = input.height)

    feature inlet_plane = plane.offset(base = origin.yz, distance = input.bowl / 2 - 5 mm)
    sketch inlet_s on plane.inlet_plane {{
        pipe = circle(center = [0 mm, input.port_height], radius = input.port / 2)
    }}
    feature inlet = extrude(profile = sketch.inlet_s, distance = input.port_length + 5 mm, mode = add(targets = [feature.bowl.body]))

    feature outlet_plane = plane.offset(base = origin.xy, distance = -input.port_length)
    sketch outlet_s on plane.outlet_plane {{
        pipe = circle(center = [0 mm, 0 mm], radius = input.port / 2)
    }}
    sketch media_s on origin.xy {{
{loop("o", outer)}
{loop("i", inner)}
    }}
    feature media = extrude(profile = sketch.media_s, distance = input.height)

    // The cartridge's core: the oil inside the media, with the outlet port below it.
    sketch core_s on origin.xy {{
{loop("i", inner)}
    }}
    feature core = extrude(profile = sketch.core_s, distance = input.height)
    feature outlet = extrude(profile = sketch.outlet_s, distance = input.port_length + 5 mm, mode = add(targets = [feature.core.body]))

    // The oil outside the media: the bowl with its inlet, less the cartridge.
    feature oil = boolean.subtract(target = feature.bowl.body, tools = [feature.media.body, feature.core.body], keep_tools = true)

    region inlet_face : face = {{ select = [feature.inlet.face.end], expect = exactly_one, body = feature.bowl.body, label = "Inlet" }}
    region outlet_face : face = {{ select = [feature.outlet.face.start], expect = exactly_one, body = feature.core.body, label = "Outlet" }}
    region wall : face = {{
        select = [
            feature.bowl.face.side(bowl_s.wall),
            feature.bowl.face.start,
            feature.bowl.face.end,
            feature.core.face.start,
            feature.core.face.end,
            feature.inlet.face.side(inlet_s.pipe),
            feature.outlet.face.side(outlet_s.pipe),
            feature.media.face.start,
            feature.media.face.end
        ],
        expect = at_least_one,
        label = "Wall"
    }}

    output oil = {{ body = feature.bowl.body, label = "Fluid", color = "#D08A1E40" }}
    output core_oil = {{ body = feature.core.body, label = "Fluid", color = "#D08A1E40" }}
    output media = {{ body = feature.media.body, label = "Media", material = "glass_fiber_media", color = "#E8E2CF" }}
}}
'''
open(sys.argv[1] if len(sys.argv) > 1 else "filter.part", "w").write(text)
