# Writes m01_cold_plate.part beside it (python3 gen_cold_plate.py m01_cold_plate.part): module
# M01's eight cells on their gap-filler strips, the cold plate under them and its coolant.
import sys
pitch, cell_w, cell_l, cell_h = 36.0, 34.0, 500.0, 95.0
centres = [286 / 8 * k for k in (1, 3, 5, 7)]

def rect(prefix, x0, x1, y0, y1):
    p = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    n = ["front", "right", "back", "left"]
    return "\n".join(
        f"        {prefix}{n[i]} = line(start = [{p[i][0]:g} mm, {p[i][1]:g} mm], end = [{p[(i + 1) % 4][0]:g} mm, {p[(i + 1) % 4][1]:g} mm])"
        for i in range(4))

cells = []
for k in range(8):
    x0 = pitch * k
    cells.append(f'''    sketch cell_{k + 1}_s on origin.xy {{
{rect("", x0, x0 + cell_w, 0, cell_l)}
    }}
    feature cell_{k + 1} = extrude(profile = sketch.cell_{k + 1}_s, distance = input.cell_height)''')
strips = "\n".join(rect(f"s{k + 1}_", pitch * k, pitch * k + cell_w, 0, cell_l) for k in range(8))
pads = "\n".join(f'''    sketch pad_{k + 1}_s on plane.pad_plane {{
{rect("", pitch * k, pitch * k + cell_w, 0, cell_l)}
    }}
    feature pad_{k + 1} = extrude(profile = sketch.pad_{k + 1}_s, distance = input.gap_filler)''' for k in range(8))
pad_outputs = "\n".join(
    f'    output pad_{k + 1} = {{ body = feature.pad_{k + 1}.body, label = "Gap filler", material = "gap_filler_3w", color = "#E0B43C" }}'
    for k in range(8))
c = centres
w = "let.half_w"
# The serpentine's outline, starting at the inlet's left corner (see the part's comment).
pts = [
    (f"{c[0]:g} mm - {w}", "input.inlet_y"), (f"{c[0]:g} mm - {w}", "-let.turn_out"),
    (f"{c[1]:g} mm + {w}", "-let.turn_out"), (f"{c[1]:g} mm + {w}", "let.top_in"),
    (f"{c[2]:g} mm - {w}", "let.top_in"), (f"{c[2]:g} mm - {w}", "-let.turn_out"),
    (f"{c[3]:g} mm + {w}", "-let.turn_out"), (f"{c[3]:g} mm + {w}", "input.inlet_y"),
    (f"{c[3]:g} mm - {w}", "input.inlet_y"), (f"{c[3]:g} mm - {w}", "let.bottom_in"),
    (f"{c[2]:g} mm + {w}", "let.bottom_in"), (f"{c[2]:g} mm + {w}", "let.top_out"),
    (f"{c[1]:g} mm - {w}", "let.top_out"), (f"{c[1]:g} mm - {w}", "let.bottom_in"),
    (f"{c[0]:g} mm + {w}", "let.bottom_in"), (f"{c[0]:g} mm + {w}", "input.inlet_y"),
]
names = ["pass1_out", "turn_a_out", "pass2_out", "turn_b_in", "pass3_out", "turn_c_out", "pass4_out", "outlet",
         "pass4_in", "turn_c_in", "pass3_in", "turn_b_out", "pass2_in", "turn_a_in", "pass1_in", "inlet"]
serp = "\n".join(
    f"        {names[i]} = line(start = [{pts[i][0]}, {pts[i][1]}], end = [{pts[(i + 1) % 16][0]}, {pts[(i + 1) % 16][1]}])"
    for i in range(16))
walls = [n for n in names if n not in ("inlet", "outlet")]
wall_refs = ", ".join([f"feature.channel.face.side(channel_s.{n})" for n in walls] + ["feature.channel.face.start", "feature.channel.face.end"])
cell_outputs = "\n".join(
    f'    output cell_{k + 1} = {{ body = feature.cell_{k + 1}.body, label = "M01 cell {k + 1}", material = "li_ion_prismatic", color = "#2F5D8A" }}'
    for k in range(8))
bottoms = ", ".join(f"feature.cell_{k + 1}.face.start" for k in range(8))
text = f'''runmat 0.7
std 1

// Module M01 of an EV battery pack on its liquid cold plate: the eight 34 x 500 x 95 mm prismatic
// cells at a 36 mm pitch (the module of runmat-examples/fea/battery-module-cells), a 3 mm
// gap-filler strip under each cell, and a 296 x 520 x 8 mm brazed aluminium cold plate whose top
// carries a 1 mm land under each strip. The coolant (50/50 water-glycol) runs in a four-pass
// serpentine channel, 14 x 4 mm, under the cells' centre lines: in at one corner of the plate's
// rear edge, out at the other. The coolant is its own body: the plate is cut by it, so each
// channel wall is one surface with a fluid side ("Channel wall") and a plate side ("Plate
// channel wall").
//
// Laminar sizing at 2 L/min (3.333e-5 m^3/s), 1070 kg/m^3, 3.5 mPa s at 25 degC:
// A = 14 x 4 = 56 mm^2, Dh = 4 A / P = 6.22 mm, U = 0.595 m/s, Re = rho U Dh / mu = 1130.
// The cells sit on z = 0 (their bottoms); the plate's rear edge, with the ports, is y = 510 mm.
// Generated by gen_cold_plate.py (runmat-cad/wasm/tests/sim/battery-cold-plate); the channel
// size, plate thickness and pad thickness are inputs.
part m01_cold_plate {{
    input cell_height : length = {cell_h:g} mm
    input gap_filler : length = 3 mm
    input land : length = 1 mm
    input plate : length = 8 mm
    input channel_width : length = 14 mm
    input channel_depth : length = 4 mm
    input floor : length = 2 mm
    input inlet_y : length = 510 mm

    let half_w = input.channel_width / 2
    let turn_out = 6 mm
    let bottom_in = input.channel_width - let.turn_out
    let top_out = 496 mm
    let top_in = let.top_out - input.channel_width
    let plate_top = -input.gap_filler - input.land
    let plate_bottom = let.plate_top - input.plate

    // The cells, each its own body.
{chr(10).join(cells)}

    // A gap-filler strip under each cell.
    feature pad_plane = plane.offset(base = origin.xy, distance = -input.gap_filler)
{pads}

    // The plate, with its lands under the strips.
    feature plate_plane = plane.offset(base = origin.xy, distance = let.plate_bottom)
    sketch plate_s on plane.plate_plane {{
        front = line(start = [-5 mm, -10 mm], end = [291 mm, -10 mm])
        right = line(start = [291 mm, -10 mm], end = [291 mm, input.inlet_y])
        rear = line(start = [291 mm, input.inlet_y], end = [-5 mm, input.inlet_y])
        left = line(start = [-5 mm, input.inlet_y], end = [-5 mm, -10 mm])
    }}
    feature plate = extrude(profile = sketch.plate_s, distance = input.plate)
    feature land_plane = plane.offset(base = origin.xy, distance = let.plate_top)
    sketch lands_s on plane.land_plane {{
{strips.replace("s", "l", 0)}
    }}
    feature lands = extrude(profile = sketch.lands_s, distance = input.land, mode = add(targets = [feature.plate.body]))

    // The coolant: the serpentine, from the inlet's left corner round the outline.
    feature channel_plane = plane.offset(base = origin.xy, distance = let.plate_bottom + input.floor)
    sketch channel_s on plane.channel_plane {{
{serp}
    }}
    feature channel = extrude(profile = sketch.channel_s, distance = input.channel_depth)
    feature passages = boolean.subtract(target = feature.plate.body, tools = [feature.channel.body], keep_tools = true)

    region coolant_inlet : face = {{ select = [feature.channel.face.side(channel_s.inlet)], expect = exactly_one, body = feature.channel.body, label = "Coolant inlet" }}
    region coolant_outlet : face = {{ select = [feature.channel.face.side(channel_s.outlet)], expect = exactly_one, body = feature.channel.body, label = "Coolant outlet" }}
    region channel_wall : face = {{ select = [{wall_refs}], expect = at_least_one, body = feature.channel.body, label = "Channel wall" }}
    region plate_channel_wall : face = {{ select = [{wall_refs}], expect = at_least_one, body = feature.plate.body, label = "Plate channel wall" }}
    region cell_bottoms : face = {{ select = [{bottoms}], expect = at_least_one, label = "M01 cell bottom" }}

{cell_outputs}
{pad_outputs}
    output cold_plate = {{ body = feature.plate.body, label = "Cold plate", part_number = "M01-CP-01", material = "aluminum_3003", color = "#B9BFC7" }}
    output coolant = {{ body = feature.channel.body, label = "Coolant", color = "#3C8DD8" }}
}}
'''
open(sys.argv[1], "w").write(text)
