# Writes mixer.part beside it (python3 gen_mixer.py mixer.part): a six-element helical static
# mixer in a 20 mm tube, and the fluid round it.
import math, sys
R, t, E, L_el, steps = 10.0, 1.5, 6, 30.0, 6     # tube radius, plate, elements, element length, sections
L_in, L_out = 20.0, 40.0
w = R + 1.0                                       # the plate's half-width before the tube trims it
f = lambda p: f"[{p[0]:.4f} mm, {p[1]:.4f} mm]"
def rect(theta):
    c, s = math.cos(theta), math.sin(theta)
    pts = [(-w, -t / 2), (w, -t / 2), (w, t / 2), (-w, t / 2)]
    return [(x * c - y * s, x * s + y * c) for x, y in pts]
def plate(theta):
    """The plate's section: a round-edged strip, as points for a closed spline."""
    c, s = math.cos(theta), math.sin(theta)
    h = t / 2
    pts = [(x, -h) for x in (-w + h, -w / 2, 0.0, w / 2, w - h)]
    pts += [(w - h + h * math.cos(a), h * math.sin(a)) for a in (-math.pi / 4, 0.0, math.pi / 4)]
    pts += [(x, h) for x in (w - h, w / 2, 0.0, -w / 2, -w + h)]
    pts += [(-w + h - h * math.cos(a), -h * math.sin(a)) for a in (-math.pi / 4, 0.0, math.pi / 4)]
    return [(x * c - y * s, x * s + y * c) for x, y in pts]
blocks, lofts, names = [], [], []
phi = 0.0
for e in range(E):
    hand = 1 if e % 2 == 0 else -1
    sketches = []
    for j in range(steps + 1):
        z = L_in + e * L_el + L_el * j / steps
        th = phi + hand * math.pi * j / steps
        pts = rect(th)
        sk = f"e{e}_s{j}"
        ring = ", ".join(f(p) for p in plate(th))
        blocks.append(f"    feature {sk}_p = plane.offset(base = origin.xy, distance = {z:.4f} mm)\n"
                      f"    sketch {sk} on plane.{sk}_p {{\n"
                      f"        c = spline(points = [{ring}], closed)\n"
                      "    }")
        sketches.append(f"sketch.{sk}")
    lofts.append(f"    feature element_{e + 1} = loft(profiles = [{', '.join(sketches)}])")
    names.append(f"feature.element_{e + 1}.body")
    phi += math.pi / 2
splitter = rect(0.0)
text = f'''runmat 0.7
std 1

// A helical static mixer in a 20 mm tube: {E} elements, each a {t} mm plate twisted 180 degrees over
// {L_el:.0f} mm (1.5 diameters), alternately right- and left-handed and turned 90 degrees to the one
// before, so each element splits the stream its neighbor delivers. A straight splitter
// plate ahead of the first element keeps the two feeds apart until they reach it: stream A
// enters through an 8 mm side port above it ("Inlet A") and stream B through one below
// ("Inlet B").
// Laminar sizing: 2 L/min of a 0.1 Pa s, 1100 kg/m^3 resin in the 20 mm bore is 0.106 m/s,
// Re = 23; static mixers of this kind are sized for Re under about 100.
// Generated by gen_mixer.py (element count, length, plate and bore); edit there and re-run it.
part mixer {{
    input bore : length = {2 * R:.0f} mm
    input inlet_length : length = {L_in:.0f} mm
    input outlet_length : length = {L_out:.0f} mm
    input port : length = 8 mm
    input port_length : length = 15 mm

    sketch splitter_s on origin.xy {{
''' + "\n".join(f"        {n} = line(start = {f(splitter[i])}, end = {f(splitter[(i + 1) % 4])})" for i, n in enumerate("abcd")) + f'''
    }}
    feature splitter = extrude(profile = sketch.splitter_s, distance = input.inlet_length)

    // The elements, lofted through sections every 30 degrees of twist.
{chr(10).join(blocks)}
{chr(10).join(lofts)}
    feature insert = boolean.union(target = feature.splitter.body, tools = [{', '.join(names)}])

    // The plates are cut a little wide and trimmed to the bore, so their edges lie on the wall.
    sketch sleeve_s on origin.xy {{
        outside = circle(center = [0 mm, 0 mm], radius = input.bore / 2 + 4 mm)
        bore = circle(center = [0 mm, 0 mm], radius = input.bore / 2)
    }}
    feature sleeve = extrude(profile = sketch.sleeve_s, distance = input.inlet_length + {E * L_el:.0f} mm + input.outlet_length)
    feature trim = boolean.subtract(target = feature.splitter.body, tools = [feature.sleeve.body])

    // The fluid: the tube with its two side ports, less the mixer.
    sketch tube_s on origin.xy {{
        bore = circle(center = [0 mm, 0 mm], radius = input.bore / 2)
    }}
    feature tube = extrude(profile = sketch.tube_s, distance = input.inlet_length + {E * L_el:.0f} mm + input.outlet_length)
    feature port_a_p = plane.offset(base = origin.zx, distance = input.bore / 2 - 1 mm)
    sketch port_a_s on plane.port_a_p {{
        bore = circle(center = [input.inlet_length / 2, 0 mm], radius = input.port / 2)
    }}
    feature port_a = extrude(profile = sketch.port_a_s, distance = input.port_length + 1 mm, mode = add(targets = [feature.tube.body]))
    feature port_b_p = plane.offset(base = origin.zx, distance = -input.bore / 2 - input.port_length)
    sketch port_b_s on plane.port_b_p {{
        bore = circle(center = [input.inlet_length / 2, 0 mm], radius = input.port / 2)
    }}
    feature port_b = extrude(profile = sketch.port_b_s, distance = input.port_length + 1 mm, mode = add(targets = [feature.tube.body]))
    feature fluid = boolean.subtract(target = feature.tube.body, tools = [feature.splitter.body], keep_tools = true)

    region inlet_a : face = {{ select = [feature.port_a.face.end], expect = exactly_one, label = "Inlet A" }}
    region inlet_b : face = {{ select = [feature.port_b.face.start], expect = exactly_one, label = "Inlet B" }}
    region outlet : face = {{ select = [feature.tube.face.end], expect = exactly_one, label = "Outlet" }}
    region wall : face = {{
        select = [feature.tube.face.side(tube_s.bore), feature.tube.face.start, feature.port_a.face.side(port_a_s.bore), feature.port_b.face.side(port_b_s.bore)],
        expect = at_least_one,
        label = "Wall"
    }}

    output fluid = {{ body = feature.tube.body, label = "Fluid", color = "#7FB7E640" }}
    output mixer = {{ body = feature.element_1.body, label = "Mixer", part_number = "SM-20-6", material = "stainless_316l", color = "#9AA3AD" }}
}}
'''
open(sys.argv[1] if len(sys.argv) > 1 else "mixer.part", "w").write(text)
