//! The scope inventory: one row per capability the website plans, end states, claim rows and
//! FEA scope documents state, each mapped to register obligations or an explicit exclusion.
//! The rows are the `claims` of the capability ledger (docs/simulation/ledger.json); edit them
//! there when a source changes. Tests fail while any row is unmapped or points at an obligation
//! that does not exist.
use crate::{
    catalog::{Cell, Verdict},
    requirement::Requirement,
    witness::Problem,
};
use std::collections::{BTreeMap, BTreeSet};

/// Tab-separated `id, source, capability, maps`, generated by build.rs from the ledger claims.
pub const INVENTORY: &str = include_str!(concat!(env!("OUT_DIR"), "/inventory.tsv"));

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Mapping {
    /// `obligation` is `None` for a whole requirement (`REQ/*`).
    Obligation {
        requirement: String,
        obligation: Option<String>,
    },
    Excluded(String),
    External {
        owner: String,
        reason: String,
    },
}

#[derive(Clone, Debug)]
pub struct ScopeRow {
    pub id: String,
    pub source: String,
    pub capability: String,
    pub maps: Vec<Mapping>,
}

pub fn rows() -> Result<Vec<ScopeRow>, Vec<Problem>> {
    let mut rows = Vec::new();
    let mut problems = Vec::new();
    for (index, line) in INVENTORY.lines().enumerate().skip(1) {
        let location = format!("docs/simulation/ledger.json claims[{}]", index - 1);
        let fields: Vec<&str> = line.split('\t').collect();
        let [id, source, capability, maps] = fields[..] else {
            problems.push(Problem {
                location,
                message: "expected id, source, capability, maps".into(),
            });
            continue;
        };
        let mut parsed = Vec::new();
        for token in maps.split('|').map(str::trim).filter(|t| !t.is_empty()) {
            if let Some(reason) = token.strip_prefix("excluded:") {
                parsed.push(Mapping::Excluded(reason.to_string()));
            } else if let Some(rest) = token.strip_prefix("external:") {
                let (owner, reason) = rest.split_once(':').unwrap_or((rest, ""));
                parsed.push(Mapping::External {
                    owner: owner.to_string(),
                    reason: reason.to_string(),
                });
            } else if let Some((requirement, obligation)) = token.split_once('/') {
                parsed.push(Mapping::Obligation {
                    requirement: requirement.to_string(),
                    obligation: (obligation != "*").then(|| obligation.to_string()),
                });
            } else {
                problems.push(Problem {
                    location: location.clone(),
                    message: format!("unreadable mapping `{token}`"),
                });
            }
        }
        rows.push(ScopeRow {
            id: id.to_string(),
            source: source.to_string(),
            capability: capability.to_string(),
            maps: parsed,
        });
    }
    if problems.is_empty() {
        Ok(rows)
    } else {
        Err(problems)
    }
}

/// Every row has a source, a capability and at least one mapping; ids are unique; every
/// mapped requirement and obligation exists.
pub fn validate(rows: &[ScopeRow], registry: &[&Requirement]) -> Vec<Problem> {
    let mut problems = Vec::new();
    let mut ids = BTreeSet::new();
    for row in rows {
        let location = format!("scope row {}", row.id);
        if !ids.insert(row.id.clone()) {
            problems.push(Problem {
                location: location.clone(),
                message: "duplicate id".into(),
            });
        }
        if row.source.is_empty() || row.capability.is_empty() {
            problems.push(Problem {
                location: location.clone(),
                message: "missing source or capability".into(),
            });
        }
        if row.maps.is_empty() {
            problems.push(Problem {
                location: location.clone(),
                message: "unmapped: map to obligations or exclude with a reason".into(),
            });
        }
        for map in &row.maps {
            match map {
                Mapping::Obligation {
                    requirement,
                    obligation,
                } => match registry.iter().find(|r| r.id == requirement) {
                    None => problems.push(Problem {
                        location: location.clone(),
                        message: format!("unknown requirement {requirement}"),
                    }),
                    Some(r) => {
                        if let Some(obligation) = obligation {
                            if !r.obligations.iter().any(|o| o.id == obligation) {
                                problems.push(Problem {
                                    location: location.clone(),
                                    message: format!(
                                        "{requirement} has no obligation {obligation}"
                                    ),
                                });
                            }
                        }
                    }
                },
                Mapping::Excluded(reason) | Mapping::External { reason, .. } => {
                    if reason.trim().is_empty() {
                        problems.push(Problem {
                            location: location.clone(),
                            message: "exclusion needs a reason".into(),
                        });
                    }
                }
            }
        }
    }
    problems
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TraceStatus {
    Pass,
    Fail,
    /// At least one mapped cell has a witness; none failed; not all passed.
    Tied,
    Open,
    Excluded,
    External,
}

impl TraceStatus {
    pub fn label(self) -> &'static str {
        match self {
            TraceStatus::Pass => "pass",
            TraceStatus::Fail => "fail",
            TraceStatus::Tied => "tied",
            TraceStatus::Open => "open",
            TraceStatus::Excluded => "excluded",
            TraceStatus::External => "external",
        }
    }
}

pub struct Trace {
    pub status: TraceStatus,
    pub cells: usize,
    pub pass: usize,
    pub partial: usize,
    pub tagged: usize,
    pub fail: usize,
}

/// Status of a scope row from the cells of the obligations it maps to.
pub fn trace(row: &ScopeRow, cells: &[Cell]) -> Trace {
    let mut selected: BTreeMap<(&str, &str, String), Verdict> = BTreeMap::new();
    for map in &row.maps {
        if let Mapping::Obligation {
            requirement,
            obligation,
        } = map
        {
            for cell in cells {
                if cell.requirement == requirement
                    && obligation.as_deref().is_none_or(|o| o == cell.obligation)
                {
                    selected.insert(
                        (
                            cell.requirement,
                            cell.obligation,
                            format!("{:?}", cell.envelope),
                        ),
                        cell.verdict,
                    );
                }
            }
        }
    }
    let count = |v: Verdict| selected.values().filter(|x| **x == v).count();
    let (pass, fail, tagged, partial) = (
        count(Verdict::Pass),
        count(Verdict::Fail),
        count(Verdict::Tagged),
        count(Verdict::Partial),
    );
    let status = if selected.is_empty() {
        if row
            .maps
            .iter()
            .any(|m| matches!(m, Mapping::External { .. }))
        {
            TraceStatus::External
        } else {
            TraceStatus::Excluded
        }
    } else if fail > 0 {
        TraceStatus::Fail
    } else if pass == selected.len() {
        TraceStatus::Pass
    } else if pass + tagged + partial > 0 {
        TraceStatus::Tied
    } else {
        TraceStatus::Open
    };
    Trace {
        status,
        cells: selected.len(),
        pass,
        partial,
        tagged,
        fail,
    }
}
