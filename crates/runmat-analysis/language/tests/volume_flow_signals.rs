pub mod support;
use runmat_analysis_language::*;
use support::{source_module, TestHost};

fn check(body: &str) -> CheckedFeaProgram {
    FeaCompiler::new(&TestHost::default()).check(CheckRequest {
        modules: ModuleGraphRequest {
            source_root: LogicalSourcePath::new("project").unwrap(),
            root: source_module("project/main.fea", &format!("model flow {{ {body} }}"), 1),
        },
    })
}

#[test]
fn volume_flow_signals_use_cubic_meters_per_second_units() {
    let program = check("signal inlet : volume_flow_rate over constant { value = -0.2 m^3/s }");
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let signal = &program.models.values().next().unwrap().signals[0];
    assert_eq!(
        signal.quantity(),
        runmat_analysis_core::PhysicalQuantityKind::VolumeFlowRate
    );
    let runmat_analysis_core::PhysicalSignal::VolumeFlowRate(signal) = signal else {
        unreachable!()
    };
    assert_eq!(
        signal.representation,
        runmat_analysis_core::SignalRepresentation::Constant(
            runmat_analysis_core::SignalValue::Scalar(runmat_analysis_core::VolumeFlowRate::new(
                -0.2
            ))
        )
    );
}

#[test]
fn volume_flow_complex_frequency_table_preserves_both_components() {
    let program = check(
        r#"signal inlet : volume_flow_rate over frequency {
        samples = [
            { at = 10 Hz, value = { real = 2 m^3/s, imaginary = -3 m^3/s } },
            { at = 20 Hz, value = { real = 4 m^3/s, imaginary = -5 m^3/s } },
        ]
        interpolation = linear
        extrapolation = reject
    }"#,
    );
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let signal = &program.models.values().next().unwrap().signals[0];
    assert_eq!(
        signal.quantity(),
        runmat_analysis_core::PhysicalQuantityKind::VolumeFlowRate
    );
    assert_eq!(
        signal.precision(),
        runmat_analysis_core::SignalPrecision::Complex128
    );
}

#[test]
fn volume_flow_rejects_wrong_units_and_vector_values() {
    for value in ["1 kg/s", "1 m/s", "[1 m^3/s, 2 m^3/s, 3 m^3/s]"] {
        let program = check(&format!(
            "signal inlet : volume_flow_rate over constant {{ value = {value} }}"
        ));
        assert!(!program.is_valid(), "unexpectedly accepted {value}");
    }
}

#[test]
fn generated_volume_flow_retains_shared_complex_frequency_contract() {
    let host = TestHost::default().with_function(
        "project/flowSpectrum.m",
        "flowSpectrum",
        vec![runmat_types::OperationParameter {
            name: "frequency".into(),
            value: runmat_types::OperationTypePattern::NumericArray,
            arity: runmat_types::OperationParameterArity::Required,
            default: None,
        }],
        vec![runmat_types::OperationTypePattern::NumericArray],
    );
    let source = r#"
import function flowSpectrum from "./flowSpectrum.m"
model flow {
    signal inlet : volume_flow_rate over frequency {
        generated by function.flowSpectrum {
            arguments {}
            sample_points = [10 Hz, 17 Hz, 20 Hz]
            precision = complex128
            interpolation = linear
            extrapolation = reject
        }
    }
}
"#;
    let program = FeaCompiler::new(&host).check(CheckRequest {
        modules: ModuleGraphRequest {
            source_root: LogicalSourcePath::new("project").unwrap(),
            root: source_module("project/main.fea", source, 1),
        },
    });
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let signal = &program.models.values().next().unwrap().signals[0];
    assert_eq!(
        signal.quantity(),
        runmat_analysis_core::PhysicalQuantityKind::VolumeFlowRate
    );
    assert_eq!(
        signal.precision(),
        runmat_analysis_core::SignalPrecision::Complex128
    );
    let generator = signal.generator().unwrap();
    assert_eq!(
        generator.domain,
        runmat_analysis_core::GeneratorDomain::FrequencyHertz
    );
    assert_eq!(
        generator.sampling,
        runmat_analysis_core::SignalSamplingPolicy::CanonicalPoints(vec![10.0, 17.0, 20.0])
    );
}
