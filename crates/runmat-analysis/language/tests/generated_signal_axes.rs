pub mod support;

use runmat_analysis_core::{GeneratorDomain, SignalPrecision, SignalSamplingPolicy};
use runmat_analysis_language::*;
use support::{source_module, TestHost};

fn check(domain: &str, members: &str) -> CheckedFeaProgram {
    check_effects(domain, members, runmat_types::EffectSet::default())
}

fn check_effects(
    domain: &str,
    members: &str,
    effects: runmat_types::EffectSet,
) -> CheckedFeaProgram {
    let host = TestHost::default().with_effectful_function(
        "project/response.m",
        "response",
        vec![runmat_types::OperationParameter {
            name: "axis".into(),
            value: runmat_types::OperationTypePattern::NumericArray,
            arity: runmat_types::OperationParameterArity::Required,
            default: None,
        }],
        vec![runmat_types::OperationTypePattern::NumericArray],
        effects,
    );
    let source = format!(
        r#"
import function response from "./response.m"
model forcing {{
    signal drive : force over {domain} {{
        generated by function.response {{
            arguments {{}}
            {members}
            interpolation = linear
            extrapolation = reject
        }}
    }}
}}
"#
    );
    FeaCompiler::new(&host).check(CheckRequest {
        modules: ModuleGraphRequest {
            source_root: LogicalSourcePath::new("project").unwrap(),
            root: source_module("project/main.fea", &source, 1),
        },
    })
}

#[test]
fn generated_physical_axes_and_complex_precision_survive_lowering() {
    for (domain, member, expected, points, precision) in [
        (
            "frequency",
            "sample_points = [10 Hz, 17 Hz, 20 Hz]\nprecision = complex128",
            GeneratorDomain::FrequencyHertz,
            vec![10.0, 17.0, 20.0],
            SignalPrecision::Complex128,
        ),
        (
            "frequency",
            "sample_points = [0 Hz, 1 kHz]",
            GeneratorDomain::FrequencyHertz,
            vec![0.0, 1000.0],
            SignalPrecision::Real64,
        ),
        (
            "time",
            "sample_points = [-1 s, 0 s, 6 ms]",
            GeneratorDomain::TimeSeconds,
            vec![-1.0, 0.0, 0.006],
            SignalPrecision::Real64,
        ),
    ] {
        let program = check(domain, member);
        assert!(
            program.is_valid(),
            "{domain}: {member}: semantic={:?} binding={:?} graph={:?}",
            program.diagnostics,
            program.bound.diagnostics,
            program.bound.graph.diagnostics
        );
        let signal = &program.models.values().next().unwrap().signals[0];
        let generator = signal.generator().unwrap();
        assert_eq!(generator.domain, expected);
        assert_eq!(
            generator.sampling,
            SignalSamplingPolicy::CanonicalPoints(points)
        );
        let runmat_analysis_core::PhysicalSignal::Force(signal) = signal else {
            panic!("force signal expected")
        };
        assert_eq!(signal.precision, precision);
    }
}

#[test]
fn generated_signal_purity_agrees_with_callable_admission() {
    use runmat_types::{EffectKind, EffectSet};
    use std::collections::BTreeSet;
    let members = "sample_points = [0.2 Hz, 0.4 Hz]\nprecision = complex128";
    assert!(check_effects(
        "frequency",
        members,
        EffectSet(BTreeSet::from([EffectKind::MayThrow]))
    )
    .is_valid());
    for forbidden in [
        EffectKind::Unknown,
        EffectKind::Network,
        EffectKind::Randomness,
        EffectKind::WorkspaceRead,
        EffectKind::FilesystemRead,
        EffectKind::HostCallback,
        EffectKind::MaySuspend,
    ] {
        let program = check_effects(
            "frequency",
            members,
            EffectSet(BTreeSet::from([EffectKind::MayThrow, forbidden])),
        );
        assert!(!program.is_valid(), "{forbidden:?}");
        assert!(program
            .diagnostics
            .iter()
            .any(|diagnostic| diagnostic.message.contains("generator must be pure")));
    }
}

#[test]
fn generated_axes_fail_closed_on_ambiguity_units_order_and_precision() {
    for (domain, member) in [
        ("frequency", "sample_points = [10 s, 20 s]"),
        ("frequency", "sample_points = [10 Hz]"),
        ("frequency", "sample_points = [20 Hz, 10 Hz]"),
        ("frequency", "sample_points = [10 Hz, 10 Hz]"),
        ("frequency", "sample_points = [-1 Hz, 10 Hz]"),
        (
            "frequency",
            "sample_points = [10 Hz, 20 Hz]\nsample_points = [1 Hz, 2 Hz]",
        ),
        (
            "frequency",
            "sample_points = [10 Hz, 20 Hz]\nsample from 0 s to 1 s at 10 Hz",
        ),
        (
            "frequency",
            "sample_points = [10 Hz, 20 Hz]\nprecision = imaginary",
        ),
        (
            "frequency",
            "sample_points = [10 Hz, 20 Hz]\nprecision = real64\nprecision = complex128",
        ),
        ("time", "sample_points = [10 Hz, 20 Hz]"),
    ] {
        let program = check(domain, member);
        assert!(
            program.bound.graph.is_valid(),
            "malformed test syntax: {:?}",
            program.bound.graph.diagnostics
        );
        assert!(
            !program.is_valid(),
            "unexpected admission: {domain}: {member}"
        );
        assert!(
            program
                .diagnostics
                .iter()
                .any(|diagnostic| diagnostic.message.contains("sample_points")
                    || diagnostic.message.contains("precision")),
            "wrong rejection: {:?}",
            program.diagnostics
        );
    }
}
