fn check(source: &str) -> CheckedFeaProgram {
    FeaCompiler::new(&TestHost::default()).check(CheckRequest {
        modules: ModuleGraphRequest {
            source_root: LogicalSourcePath::new("project").unwrap(),
            root: source_module("project/main.fea", source, 1),
        },
    })
}

// witness: FEA-AUTHORING-LANGUAGE-002/spectral_inputs @
//   shared_infrastructure/mesh_independent/source_check; coverage: partial;
//   boundary: A response spectrum is a typed model-owned input retaining the complete solver policy
//   (combination rules, mass truncation, rigid response); procedure references through the bound
//   model are covered by sibling tests only.
#[test]
fn response_spectrum_is_typed_and_retains_complete_solver_policy() {
    let program = check(
        r#"
model launch_environment {
    response_spectrum launch_x {
        frequencies = [5, 10, 20] Hz
        ordinates = [2, 4, 1] g
        damping_ratio = 0.05
        response = pseudo_acceleration
        direction = [1, 0, 0]
        modal_combination = cqc
        directional_combination = percentage
        primary_percentage = 1.0
        secondary_percentage = 0.3
        minimum_cumulative_mass_ratio = 0.95
        truncation_correction = missing_mass
        zero_period_acceleration = 1 g
        rigid_response = gupta
        periodic_frequency = 15 Hz
        rigid_frequency = 25 Hz
        sampling_adequacy_ratio = 1.0
    }
}
"#,
    );
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let model = program.models.values().next().unwrap();
    let spectrum = &model.response_spectra[0];
    assert_eq!(spectrum.response, SpectrumResponse::PseudoAcceleration);
    assert_eq!(
        spectrum.modal_combination,
        ModalCombination::CompleteQuadraticCombination
    );
    assert_eq!(
        spectrum.directional_combination,
        DirectionalCombination::PercentageRule {
            primary: 1.0,
            secondary: 0.3,
        }
    );
    assert!(matches!(
        spectrum.truncation.correction,
        ModalTruncationCorrection::MissingMass { .. }
    ));
    assert!(matches!(
        spectrum.rigid_response,
        RigidResponsePolicy::Gupta { .. }
    ));
    assert_eq!(spectrum.resolved_ordinates().unwrap()[0], 2.0 * 9.806_65);
}

#[test]
fn random_excitation_retains_correlated_complex_cross_spectra() {
    let program = check(
        r#"
model launch_environment {
    random_excitation launch_random {
        frequencies = [10, 20] Hz
        channels = [
            { id = "x", quantity = base_acceleration, direction = [1, 0, 0] },
            { id = "y", quantity = base_acceleration, direction = [0, 1, 0] }
        ]
        spectral_density_real = [
            [[4, 0], [0, 1]],
            [[9, 0], [0, 4]]
        ] m^2/s^3
        spectral_density_imaginary = [
            [[0, 2], [-2, 0]],
            [[0, 3], [-3, 0]]
        ] m^2/s^3
        convention = one_sided_per_hertz
        interpolation = linear_frequency
        extrapolation = reject
        max_absolute_density_error = 0 m^2/s^3
        equivalent_degrees_of_freedom = 32
    }
}
"#,
    );
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let excitation = &program.models.values().next().unwrap().random_excitations[0];
    assert_eq!(excitation.channels.len(), 2);
    let samples = excitation.resolved_spectral_density().unwrap();
    assert_eq!(samples.len(), 2);
    assert_eq!(samples[0].canonical_coefficient(2, 0, 1).imaginary, 2.0);
    assert_eq!(samples[0].canonical_coefficient(2, 1, 0).imaginary, -2.0);
}

#[test]
fn spectral_generators_bind_exact_imported_callable_facts() {
    let source = r#"
import function designCurve from "./designCurve.m"
import function crossSpectrum from "./crossSpectrum.m"

model launch_environment {
    response_spectrum launch_x {
        frequencies = [5, 10, 20] Hz
        generated by function.designCurve { arguments {} }
        damping_ratio = 0.05
        response = pseudo_acceleration
        direction = [1, 0, 0]
    }
    random_excitation broadband {
        frequencies = [5, 10, 20] Hz
        channels = [{ id = "x", quantity = base_acceleration, direction = [1, 0, 0] }]
        generated by function.crossSpectrum { arguments {} }
    }
}
"#;
    let axis = runmat_types::OperationParameter {
        name: "frequency".to_string(),
        value: runmat_types::OperationTypePattern::NumericArray,
        arity: runmat_types::OperationParameterArity::Required,
        default: None,
    };
    let host = TestHost::default()
        .with_function(
            "project/designCurve.m",
            "designCurve",
            vec![axis.clone()],
            vec![runmat_types::OperationTypePattern::NumericArray],
        )
        .with_function(
            "project/crossSpectrum.m",
            "crossSpectrum",
            vec![axis],
            vec![runmat_types::OperationTypePattern::NumericArray],
        );
    let program = FeaCompiler::new(&host).check(CheckRequest {
        modules: ModuleGraphRequest {
            source_root: LogicalSourcePath::new("project").unwrap(),
            root: source_module("project/main.fea", source, 1),
        },
    });
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let model = program.models.values().next().unwrap();
    assert_eq!(
        model.response_spectra[0]
            .ordinates
            .generator()
            .unwrap()
            .callable
            .display_name(),
        "designCurve"
    );
    assert_eq!(
        model.random_excitations[0]
            .spectral_density
            .generator()
            .unwrap()
            .callable
            .display_name(),
        "crossSpectrum"
    );
}

#[test]
fn invalid_spectral_shapes_and_closed_values_are_diagnostics() {
    let program = check(
        r#"
model invalid {
    response_spectrum bad_response {
        frequencies = [5, 10] Hz
        ordinates = [1, 2] g
        damping_ratio = 0.05
        response = mystery_response
        direction = [1, 0, 0]
    }
    random_excitation bad_random {
        frequencies = [10, 20] Hz
        channels = [{ id = "x", quantity = base_acceleration, direction = [1, 0, 0] }]
        spectral_density_real = [[[1]], [[1, 2]]] m^2/s^3
    }
}
"#,
    );
    assert!(!program.is_valid());
    assert!(program.models.is_empty());
    let messages = program
        .diagnostics
        .iter()
        .map(|diagnostic| diagnostic.message.as_str())
        .collect::<Vec<_>>();
    assert!(messages
        .iter()
        .any(|message| message.contains("unsupported response-spectrum `response`")));
    assert!(
        messages
            .iter()
            .any(|message| message.contains("regular numeric array")
                || message.contains("rank-three array")),
        "{messages:#?}"
    );
}

#[test]
fn procedures_resolve_model_owned_spectra_and_realization_carries_them() {
    let program = check(
        r#"
geometry part {
    construct {
        feature body = box(width = 1 m, depth = 1 m, height = 1 m)
        result = feature.body
    }
}
mesh part on geometry.part {
    tetrahedra {
        order = linear
        target_size = 0.1 m
        maximum_deviation = 0.01 m
    }
}
model spectral_environment {
    response_spectrum design {
        frequencies = [5, 10] Hz
        ordinates = [2, 1] g
        damping_ratio = 0.05
        response = pseudo_acceleration
        direction = [1, 0, 0]
    }
    random_excitation broadband {
        frequencies = [5, 10] Hz
        channels = [{ id = "x", quantity = base_acceleration, direction = [1, 0, 0] }]
        spectral_density_real = [[[1]], [[2]]] m^2/s^3
    }
}
model environment {
    include model.spectral_environment
}
study qualification {
    geometry = geometry.part
    mesh = mesh.part
    model = model.environment
    analysis modes {
        structural modal { modes = 4 }
        retain basis
    }
    analysis spectrum after analysis.modes {
        structural modal_response_spectrum {
            basis = analysis.modes.state.basis
            spectra = [model.response_spectrum.design]
        }
    }
    analysis random after analysis.modes {
        structural random_response {
            basis = analysis.modes.state.basis
            excitation = model.random_excitation.broadband
            modal_damping_ratio = 0.03
            minimum_cumulative_mass_ratio = 0.95
        }
    }
}
"#,
    );
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let resolved = program
        .resolve_study("project/main.fea", "qualification")
        .unwrap();
    let realized_study = resolved
        .study
        .realize_with_models(&resolved.models, &resolved.geometry, &[])
        .unwrap();
    let realized = runmat_analysis_core::realize_analysis_model(
        runmat_analysis_core::AnalysisModelRealizationInput {
            study: &realized_study,
            geometry_id: "part",
            geometry_revision: 1,
            units: runmat_types::physical::CoordinateUnits::canonical(),
            regions: &Default::default(),
            materials: &resolved.material_catalog,
        },
    )
    .unwrap();
    assert_eq!(realized.model.response_spectra.len(), 1);
    assert_eq!(realized.model.random_excitations.len(), 1);
    assert_eq!(realized.model.sequence.steps.len(), 3);
}
