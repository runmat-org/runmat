pub mod support;

use runmat_analysis_core::{
    AuthoredSignalFieldLocation, AuthoredSignalTopologySelector, SignalShape,
};
use runmat_analysis_language::*;
use support::{source_module, TestHost};

fn check(quantity: &str, members: &str) -> CheckedFeaProgram {
    check_model(quantity, members, "")
}

fn check_model(quantity: &str, members: &str, model_members: &str) -> CheckedFeaProgram {
    let host = TestHost::default().with_function(
        "project/field.m",
        "field",
        vec![runmat_types::OperationParameter {
            name: "axis".into(),
            value: runmat_types::OperationTypePattern::NumericArray,
            arity: runmat_types::OperationParameterArity::Required,
            default: None,
        }],
        vec![runmat_types::OperationTypePattern::NumericArray],
    );
    let source = format!(
        r#"
import function field from "./field.m"
model forcing {{
    signal drive : {quantity} over time {{
        {members}
        generated by function.field {{
            arguments {{}}
            sample_points = [0 s, 1 s]
            interpolation = linear
            extrapolation = reject
        }}
    }}
    {model_members}
}}
"#
    );
    FeaCompiler::new(&host).check(CheckRequest {
        modules: ModuleGraphRequest {
            source_root: LogicalSourcePath::new("project").unwrap(),
            root: source_module("project/main.fea", &source, 1),
        },
    })
}

#[test]
fn authored_body_field_excitation_uses_typed_spatial_distribution() {
    let program = check_model("body_force_density",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 3\nframe = global",
        "excitation density { body_force { target = whole_model\nsignal = signal.drive } }\nload_case field_case { include excitation.density }");
    assert!(program.is_valid(), "{:#?}", program.diagnostics);
    let model = program.models.values().next().unwrap();
    assert_eq!(
        model.excitations[0].distribution,
        runmat_analysis_core::ExcitationDistribution::TopologyField
    );
}

#[test]
fn authored_scalar_and_vector_fields_keep_deferred_typed_topology() {
    for (quantity, width, frame) in [
        ("temperature", 1, ""),
        ("body_force_density", 3, "frame = global"),
    ] {
        for (name, location) in [
            ("node", AuthoredSignalFieldLocation::Node),
            ("cell", AuthoredSignalFieldLocation::Cell),
            ("element", AuthoredSignalFieldLocation::Element),
            ("face", AuthoredSignalFieldLocation::Face),
            ("edge", AuthoredSignalFieldLocation::Edge),
        ] {
            let program = check(quantity, &format!("topology = study_solver_mesh\nlocation = {name}\ncomponents = {width}\n{frame}"));
            assert!(program.is_valid(), "{:#?}", program.diagnostics);
            let signal = &program.models.values().next().unwrap().signals[0];
            assert_eq!(
                signal.shape(),
                &SignalShape::DeferredTopologyField {
                    selector: AuthoredSignalTopologySelector::StudySolverMesh { location },
                    component_count: width,
                }
            );
            assert_eq!(signal.shape().realized_component_count(Some(42)), None);
            assert!(signal.generator().is_some());
        }
    }
}

#[test]
fn authored_field_metadata_rejects_ambiguity_unknown_members_and_missing_frame() {
    for members in [
        "topology = guessed_mesh\nlocation = node\ncomponents = 3\nframe = global",
        "topology = study_solver_mesh\nlocation = integration_point\ncomponents = 3\nframe = global",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 0\nframe = global",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 1.5\nframe = global",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 18446744073709551616\nframe = global",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 3",
        "topology = study_solver_mesh\nlocation = node\nframe = global",
        "location = node\ncomponents = 3\nframe = global",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 3\ncomponents = 3\nframe = global",
        "topology = study_solver_mesh\nlocation = node\ncomponents = 3\nframe = global\nframe = global",
        "frame = global\ninvented = 1",
    ] {
        let program = check("body_force_density", members);
        assert!(!program.is_valid(), "accepted {members}");
        assert!(program.models.is_empty(), "invalid field was published: {members}");
    }
}

#[test]
fn ordinary_generated_scalar_vector_shapes_remain_unchanged() {
    for (members, shape) in [
        ("", SignalShape::Scalar),
        ("frame = global", SignalShape::Vector3),
    ] {
        let program = check("force", members);
        assert!(program.is_valid(), "{:#?}", program.diagnostics);
        assert_eq!(
            program.models.values().next().unwrap().signals[0].shape(),
            &shape
        );
    }
}
