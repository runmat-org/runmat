use super::{diagnostic, optional_frame, scalar, SignalWrapper};
use crate::{
    semantic::expression::operation_pattern_matches, BoundFeaProgram, CheckedExpression,
    CheckedExpressionKind, CheckedFeaDeclaration, CheckedFeaStatement, CheckedFeaStatementKind,
    FeaDiagnostic, FeaType, PhysicalDimension,
};
use runmat_analysis_core::{
    GeneratorArgument, GeneratorCallable, GeneratorDomain, GeneratorEffectPolicy,
    GeneratorInvocation, ImportedFunctionIdentity, PhysicalSignal, Signal,
    SignalApproximationEvidence, SignalGenerator, SignalId, SignalPrecision, SignalProvenance,
    SignalRepresentation, SignalSamplingPolicy, SignalShape,
};
use runmat_types::{OperationParameterArity, OperationTypePattern};
use std::collections::BTreeMap;

pub(super) struct LowerSignal<'a> {
    pub declaration: &'a CheckedFeaDeclaration,
    pub bound: &'a BoundFeaProgram,
    pub quantity_dimension: PhysicalDimension,
    pub wrap: SignalWrapper,
    pub diagnostics: &'a mut Vec<FeaDiagnostic>,
}

pub(super) fn lower(
    context: LowerSignal<'_>,
    id: &str,
    domain: &str,
    body: &[CheckedFeaStatement],
) -> Option<PhysicalSignal> {
    let LowerSignal {
        declaration,
        bound,
        quantity_dimension,
        wrap,
        diagnostics,
    } = context;
    let generators = body
        .iter()
        .filter_map(|statement| match &statement.kind {
            CheckedFeaStatementKind::GeneratedByFunction {
                function,
                statements,
            } => Some((function, statements.as_slice())),
            _ => None,
        })
        .collect::<Vec<_>>();
    if generators.len() != 1 {
        error(
            declaration,
            declaration.span,
            "generated signal requires exactly one `generated by function.<name>` block",
            diagnostics,
        );
        return None;
    }
    for statement in body {
        if !matches!(
            statement.kind,
            CheckedFeaStatementKind::GeneratedByFunction { .. }
                | CheckedFeaStatementKind::Assignment { .. }
        ) {
            error(
                declaration,
                statement.span,
                "generated signal body accepts only its generator and optional frame",
                diagnostics,
            );
        }
    }
    let (function, statements) = generators[0];
    let [namespace, imported_name] = function.as_slice() else {
        error(
            declaration,
            declaration.span,
            "generator must reference one imported function",
            diagnostics,
        );
        return None;
    };
    if namespace != "function" {
        error(
            declaration,
            declaration.span,
            "generator reference must use the `function` namespace",
            diagnostics,
        );
        return None;
    }
    let Some(facts) = bound
        .functions
        .get(&(declaration.module.clone(), imported_name.clone()))
    else {
        error(
            declaration,
            declaration.span,
            format!("generated signal references unknown imported function `{imported_name}`"),
            diagnostics,
        );
        return None;
    };
    validate_callable(declaration, facts, "signal", diagnostics);
    let arguments = arguments(declaration, facts, statements, "signal", diagnostics)?;
    let (sampling, tolerance) = sampling(
        declaration,
        domain,
        quantity_dimension,
        statements,
        diagnostics,
    )?;
    let domain = generator_domain(declaration, domain, diagnostics)?;
    let interpolation = super::policy::interpolation(declaration, statements, diagnostics)?;
    let extrapolation = super::policy::extrapolation(declaration, statements, diagnostics)?;
    validate_generator_members(declaration, statements, diagnostics);

    let vector = body.iter().any(|statement| {
        matches!(&statement.kind, CheckedFeaStatementKind::Assignment { target, .. } if target.as_slice() == ["frame"])
    });
    let frame = optional_frame(declaration, body, vector, diagnostics)?;
    let shape = if vector {
        SignalShape::Vector3
    } else {
        SignalShape::Scalar
    };
    let callable = GeneratorCallable::ImportedFunction(Box::new(ImportedFunctionIdentity {
        module_path: facts.module_path.as_str().to_string(),
        symbol: facts.symbol.as_str().to_string(),
        source_digest: hex_digest(facts.source_digest.0),
    }));
    Some(wrap(Signal {
        signal_id: SignalId(id.into()),
        shape,
        frame,
        representation: SignalRepresentation::Generator(SignalGenerator {
            invocation: GeneratorInvocation {
                callable,
                arguments,
                effects: GeneratorEffectPolicy::Pure,
            },
            domain,
            sampling,
            interpolation,
            extrapolation,
        }),
        precision: SignalPrecision::Real64,
        evidence: SignalApproximationEvidence {
            max_absolute_error: tolerance,
            max_relative_error: None,
            derivative_max_absolute_error: None,
            sample_count: 0,
        },
        provenance: SignalProvenance::Authored,
    }))
}

fn validate_callable(
    declaration: &CheckedFeaDeclaration,
    facts: &crate::FunctionFacts,
    label: &str,
    diagnostics: &mut Vec<FeaDiagnostic>,
) {
    if !facts.effects.0.is_empty() {
        error(
            declaration,
            declaration.span,
            format!("{label} generator must be pure; effectful functions are not admitted"),
            diagnostics,
        );
    }
    if !matches!(
        facts.inputs.first(),
        Some(parameter)
            if parameter.arity == OperationParameterArity::Required
                && parameter.value == OperationTypePattern::NumericArray
    ) {
        error(
            declaration,
            declaration.span,
            format!(
                "{label} generator first input must be the required numeric sample-axis vector"
            ),
            diagnostics,
        );
    }
    if facts.outputs.as_slice() != [OperationTypePattern::NumericArray] {
        error(
            declaration,
            declaration.span,
            format!("{label} generator must return exactly one numeric array"),
            diagnostics,
        );
    }
}

fn arguments(
    declaration: &CheckedFeaDeclaration,
    facts: &crate::FunctionFacts,
    statements: &[CheckedFeaStatement],
    label: &str,
    diagnostics: &mut Vec<FeaDiagnostic>,
) -> Option<Vec<GeneratorArgument>> {
    let blocks = statements
        .iter()
        .filter_map(|statement| match &statement.kind {
            CheckedFeaStatementKind::Block {
                header, statements, ..
            } if header.trim() == "arguments" => Some(statements.as_slice()),
            _ => None,
        })
        .collect::<Vec<_>>();
    if blocks.len() != 1 {
        error(
            declaration,
            declaration.span,
            format!("generated {label} requires exactly one `arguments` block"),
            diagnostics,
        );
        return None;
    }
    let mut authored = BTreeMap::new();
    for statement in blocks[0] {
        let CheckedFeaStatementKind::Assignment { target, value, .. } = &statement.kind else {
            error(
                declaration,
                statement.span,
                "generator arguments must be named assignments",
                diagnostics,
            );
            continue;
        };
        let [name] = target.as_slice() else {
            error(
                declaration,
                statement.span,
                "generator argument names cannot be qualified",
                diagnostics,
            );
            continue;
        };
        if authored.insert(name.as_str(), value).is_some() {
            error(
                declaration,
                statement.span,
                format!("duplicate generator argument `{name}`"),
                diagnostics,
            );
        }
    }
    let mut result = Vec::new();
    for parameter in facts.inputs.iter().skip(1) {
        let Some(value) = authored.remove(parameter.name.as_str()) else {
            if parameter.arity == OperationParameterArity::Required {
                error(
                    declaration,
                    declaration.span,
                    format!("{label} generator requires argument `{}`", parameter.name),
                    diagnostics,
                );
            }
            continue;
        };
        if !operation_pattern_matches(&parameter.value, &value.value_type) {
            error(
                declaration,
                value.span,
                format!(
                    "{label} generator argument `{}` has an incompatible type",
                    parameter.name
                ),
                diagnostics,
            );
            continue;
        }
        if let Some(value) = generator_argument(value) {
            result.push(value);
        } else {
            error(
                declaration,
                value.span,
                format!(
                    "{label} generator argument `{}` must be a closed constant value",
                    parameter.name
                ),
                diagnostics,
            );
        }
    }
    for name in authored.keys() {
        error(
            declaration,
            declaration.span,
            format!("{label} generator does not declare argument `{name}`"),
            diagnostics,
        );
    }
    Some(result)
}

pub(in crate::semantic::model) fn lower_numerical_invocation(
    declaration: &CheckedFeaDeclaration,
    bound: &BoundFeaProgram,
    body: &[CheckedFeaStatement],
    label: &str,
    diagnostics: &mut Vec<FeaDiagnostic>,
) -> Option<GeneratorInvocation> {
    let generators = body
        .iter()
        .filter_map(|statement| match &statement.kind {
            CheckedFeaStatementKind::GeneratedByFunction {
                function,
                statements,
            } => Some((function, statements.as_slice())),
            _ => None,
        })
        .collect::<Vec<_>>();
    if generators.len() != 1 {
        error(
            declaration,
            declaration.span,
            format!("generated {label} requires exactly one imported function"),
            diagnostics,
        );
        return None;
    }
    let (function, statements) = generators[0];
    let [namespace, imported_name] = function.as_slice() else {
        error(
            declaration,
            declaration.span,
            "generator must reference one imported function",
            diagnostics,
        );
        return None;
    };
    if namespace != "function" {
        error(
            declaration,
            declaration.span,
            "generator reference must use the `function` namespace",
            diagnostics,
        );
        return None;
    }
    let facts = bound
        .functions
        .get(&(declaration.module.clone(), imported_name.clone()))
        .or_else(|| {
            error(
                declaration,
                declaration.span,
                format!("generated {label} references unknown imported function `{imported_name}`"),
                diagnostics,
            );
            None
        })?;
    if statements.len() != 1
        || !matches!(
            &statements[0].kind,
            CheckedFeaStatementKind::Block { header, .. } if header.trim() == "arguments"
        )
    {
        error(
            declaration,
            declaration.span,
            format!("generated {label} accepts exactly one `arguments` block"),
            diagnostics,
        );
        return None;
    }
    validate_callable(declaration, facts, label, diagnostics);
    let arguments = arguments(declaration, facts, statements, label, diagnostics)?;
    Some(GeneratorInvocation {
        callable: GeneratorCallable::ImportedFunction(Box::new(ImportedFunctionIdentity {
            module_path: facts.module_path.as_str().to_string(),
            symbol: facts.symbol.as_str().to_string(),
            source_digest: hex_digest(facts.source_digest.0),
        })),
        arguments,
        effects: GeneratorEffectPolicy::Pure,
    })
}

fn generator_argument(value: &CheckedExpression) -> Option<GeneratorArgument> {
    match &value.kind {
        CheckedExpressionKind::Boolean(value) => Some(GeneratorArgument::Boolean(*value)),
        CheckedExpressionKind::String(value) => Some(GeneratorArgument::Text(value.clone())),
        CheckedExpressionKind::Number(source) if value.value_type == FeaType::Integer => source
            .parse::<i64>()
            .ok()
            .map(GeneratorArgument::SignedInteger),
        CheckedExpressionKind::List(values) => values
            .iter()
            .map(scalar)
            .collect::<Option<Vec<_>>>()
            .map(GeneratorArgument::RealVector),
        _ => scalar(value).map(GeneratorArgument::Real),
    }
}

fn sampling(
    declaration: &CheckedFeaDeclaration,
    domain: &str,
    quantity_dimension: PhysicalDimension,
    statements: &[CheckedFeaStatement],
    diagnostics: &mut Vec<FeaDiagnostic>,
) -> Option<(SignalSamplingPolicy, Option<f64>)> {
    let samples = statements
        .iter()
        .filter_map(|statement| match &statement.kind {
            CheckedFeaStatementKind::UniformSample { start, end, rate } => Some((start, end, rate)),
            _ => None,
        })
        .collect::<Vec<_>>();
    if samples.len() != 1 {
        error(
            declaration,
            declaration.span,
            "generated signal requires exactly one uniform sampling declaration",
            diagnostics,
        );
        return None;
    }
    let (start, end, rate) = samples[0];
    if domain != "time"
        || start.value_type != FeaType::Quantity(PhysicalDimension::TIME)
        || end.value_type != FeaType::Quantity(PhysicalDimension::TIME)
        || rate.value_type != FeaType::Quantity(PhysicalDimension::FREQUENCY)
    {
        error(
            declaration,
            start.span,
            "uniform generated sampling currently requires a time domain, time bounds, and frequency rate",
            diagnostics,
        );
        return None;
    }
    let start = scalar(start)?;
    let end = scalar(end)?;
    let rate = scalar(rate)?;
    let intervals = (end - start) * rate;
    let rounded = intervals.round();
    if !start.is_finite()
        || !end.is_finite()
        || !rate.is_finite()
        || start >= end
        || rate <= 0.0
        || (intervals - rounded).abs() > 1e-9 * intervals.abs().max(1.0)
        || rounded > (usize::MAX - 1) as f64
    {
        error(
            declaration,
            declaration.span,
            "sampling bounds and rate must define at least two finite, exactly spaced samples",
            diagnostics,
        );
        return None;
    }
    let tolerance = assignment(statements, "tolerance").and_then(|value| {
        if value.value_type != FeaType::Quantity(quantity_dimension) {
            error(
                declaration,
                value.span,
                "signal tolerance must have the declared signal quantity",
                diagnostics,
            );
            None
        } else {
            scalar(value)
        }
    });
    if tolerance.is_some_and(|value| !value.is_finite() || value <= 0.0) {
        error(
            declaration,
            declaration.span,
            "signal tolerance must be finite and positive",
            diagnostics,
        );
        return None;
    }
    Some((
        SignalSamplingPolicy::Uniform {
            start,
            end,
            sample_count: rounded as usize + 1,
        },
        tolerance,
    ))
}

fn generator_domain(
    declaration: &CheckedFeaDeclaration,
    domain: &str,
    diagnostics: &mut Vec<FeaDiagnostic>,
) -> Option<GeneratorDomain> {
    match domain {
        "time" => Some(GeneratorDomain::TimeSeconds),
        "frequency" => Some(GeneratorDomain::FrequencyHertz),
        _ => {
            error(
                declaration,
                declaration.span,
                format!("unsupported generated signal domain `{domain}`"),
                diagnostics,
            );
            None
        }
    }
}

fn validate_generator_members(
    declaration: &CheckedFeaDeclaration,
    statements: &[CheckedFeaStatement],
    diagnostics: &mut Vec<FeaDiagnostic>,
) {
    let mut seen = BTreeMap::new();
    for statement in statements {
        let name = match &statement.kind {
            CheckedFeaStatementKind::Block { header, .. } if header.trim() == "arguments" => {
                "arguments"
            }
            CheckedFeaStatementKind::UniformSample { .. } => "sample",
            CheckedFeaStatementKind::Assignment { target, .. }
                if target.len() == 1
                    && ["interpolation", "extrapolation", "tolerance"]
                        .contains(&target[0].as_str()) =>
            {
                target[0].as_str()
            }
            _ => {
                error(
                    declaration,
                    statement.span,
                    "unsupported generated-signal member",
                    diagnostics,
                );
                continue;
            }
        };
        if seen.insert(name, statement.span).is_some() {
            error(
                declaration,
                statement.span,
                format!("duplicate generated-signal member `{name}`"),
                diagnostics,
            );
        }
    }
}

fn assignment<'a>(
    statements: &'a [CheckedFeaStatement],
    name: &str,
) -> Option<&'a CheckedExpression> {
    statements
        .iter()
        .find_map(|statement| match &statement.kind {
            CheckedFeaStatementKind::Assignment { target, value, .. }
                if target.as_slice() == [name] =>
            {
                Some(value)
            }
            _ => None,
        })
}

fn hex_digest(bytes: [u8; 32]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut result = String::with_capacity(64);
    for byte in bytes {
        result.push(HEX[(byte >> 4) as usize] as char);
        result.push(HEX[(byte & 0x0f) as usize] as char);
    }
    result
}

fn error(
    declaration: &CheckedFeaDeclaration,
    span: runmat_types::Span,
    message: impl Into<String>,
    diagnostics: &mut Vec<FeaDiagnostic>,
) {
    diagnostic(declaration, span, message, diagnostics);
}
